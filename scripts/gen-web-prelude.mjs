// Regenerates packages/runtime/src/scr_web_prelude.h from
// packages/runtime/src/scr_web_prelude.js — the island's web-platform
// globals, ONE JavaScript text both engines evaluate (the native island,
// scr_web.c; the WasmGC tier's engine, wasm/isl_core.c inside engine.wasm).
// Run from the repo root:
//   node scripts/gen-web-prelude.mjs          # write the header
//   node scripts/gen-web-prelude.mjs --check  # require the checked-in one
// then rebuild the engine (node scripts/build-engine-wasm.mjs). The .js is
// the source; the header is its C string literal, checked in so a native
// build needs no generator. tests/harness/web-globals.test.ts requires the
// two to agree (renderWebPrelude over the .js == the header, byte for byte)
// and packages/compiler/test/wasm-island-engine.test.ts requires the
// engine artifact to embed the .js text.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
export const JS_PATH = join(root, "packages/runtime/src/scr_web_prelude.js");
export const H_PATH = join(root, "packages/runtime/src/scr_web_prelude.h");

const HEAD = `/* scr_web_prelude.h — GENERATED by scripts/gen-web-prelude.mjs from
 * scr_web_prelude.js; do not edit by hand (edit the .js, regenerate, rebuild
 * the wasm engine with scripts/build-engine-wasm.mjs).
 *
 * The island's web-platform globals, ONE source for both engines: the
 * native island (scr_web.c's scr_island_web_boot, every -DSCR_DYNAMIC
 * build) and the WasmGC tier's engine module (wasm/isl_core.c, compiled
 * into the checked-in vendor/quickjs-ng-wasm/engine.wasm). The text is one
 * arrow function, evaluated at engine boot and called with a HOST object —
 * the only thing the two lanes implement separately; scr_web_prelude.js
 * states its contract. SEMANTICS.md S108 states the subset. */
#ifndef SCR_WEB_PRELUDE_H
#define SCR_WEB_PRELUDE_H

static const char web_prelude[] =
`;

/** The header for the prelude text `js`. */
export function renderWebPrelude(js) {
  if (!js.endsWith("\n")) throw new Error("scr_web_prelude.js must end with a newline");
  const lines = js.slice(0, -1).split("\n");
  const body = lines.map((l) => {
    if (/[^\x09\x20-\x7e\u00a0-\uffff]/.test(l)) throw new Error(`scr_web_prelude.js: a control character in ${JSON.stringify(l)}`);
    if (/\?\?[=(/)'<!>-]/.test(l)) throw new Error(`scr_web_prelude.js: a C trigraph sequence in ${JSON.stringify(l)}`);
    return `    "${l.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}\\n"`;
  });
  return HEAD + body.join("\n") + ";\n\n#endif /* SCR_WEB_PRELUDE_H */\n";
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = renderWebPrelude(readFileSync(JS_PATH, "utf8"));
  if (process.argv.includes("--check")) {
    if (readFileSync(H_PATH, "utf8") !== out) {
      console.error(`${H_PATH} is stale: run node scripts/gen-web-prelude.mjs`);
      process.exit(1);
    }
    console.log("scr_web_prelude.h matches scr_web_prelude.js");
  } else {
    writeFileSync(H_PATH, out);
    console.log(`wrote ${H_PATH}`);
  }
}
