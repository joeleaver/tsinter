#!/usr/bin/env node
/* Generates the OS-name tables one compiled module shares with every host
 * (SEMANTICS.md S118: the module learns its OS at run time — the host
 * answers the NUMBER its OS gives each name, the module keeps only names):
 *
 *   packages/compiler/src/backend/wasm/os-names.ts
 *     SIGNAL_NAMES — Node's os.constants.signals keys, in node_constants.cc's
 *       order, over every OS Node runs on (a host answers 0 for a name its
 *       OS lacks); ERRNO_NAMES — libuv's UV_ERRNO_MAP (uv.h) in its order:
 *       util.getSystemErrorMap()'s names and messages on every OS.
 *   packages/runtime/src/wasmnative/wn_os_names.h
 *     the native hosts' answers, index for index: a signal's number where
 *     <signal.h> defines it (node_constants.cc's own #ifdef rule; Windows:
 *     the MSVC + libuv uv/win.h set Node compiles with), and an errno's
 *     libuv number through libuv's own uv/errno.h (vendored beside it as
 *     uv_errno.h — -errno on POSIX, libuv's fixed numbers on Windows).
 *
 * The libuv headers are the ones the running Node ships
 * (<prefix>/include/node/uv.h, uv/errno.h): run it with the oracle Node.
 *
 *   node scripts/gen-os-names.mjs           # rewrite the three files
 *   node scripts/gen-os-names.mjs --check   # require byte-identity */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const inc = join(dirname(process.execPath), "..", "include", "node");
const uvH = readFileSync(join(inc, "uv.h"), "utf8");
const errnoH = readFileSync(join(inc, "uv", "errno.h"), "utf8");

/* node_constants.cc DefineSignalConstants' order. The Linux keys are
 * measured (Object.keys(os.constants.signals) on Node v24.18.1);
 * SIGBREAK (Windows) and SIGINFO (macOS) sit where node_constants.cc
 * defines them. Order matters only where one OS gives two names one
 * number: the FIRST is the name a number reads back as (6 SIGABRT, never
 * SIGIOT; 29 SIGIO, never SIGPOLL — what Node reports for a child's
 * signal). */
const SIGNALS = [
  "SIGHUP", "SIGINT", "SIGQUIT", "SIGILL", "SIGTRAP", "SIGABRT", "SIGIOT", "SIGBUS", "SIGFPE", "SIGKILL",
  "SIGUSR1", "SIGSEGV", "SIGUSR2", "SIGPIPE", "SIGALRM", "SIGTERM", "SIGCHLD", "SIGSTKFLT", "SIGCONT",
  "SIGSTOP", "SIGTSTP", "SIGBREAK", "SIGTTIN", "SIGTTOU", "SIGURG", "SIGXCPU", "SIGXFSZ", "SIGVTALRM",
  "SIGPROF", "SIGWINCH", "SIGIO", "SIGPOLL", "SIGPWR", "SIGINFO", "SIGSYS",
];
/* Node on Windows: MSVC's <signal.h> (SIGINT 2, SIGILL 4, SIGFPE 8,
 * SIGSEGV 11, SIGTERM 15, SIGBREAK 21, SIGABRT 22) plus libuv's uv/win.h
 * additions (SIGHUP 1, SIGQUIT 3, SIGKILL 9, SIGWINCH 28). mingw's own
 * <signal.h> is not the one Node is built with, so the table is pinned. */
const WIN32_SIGNALS = { SIGHUP: 1, SIGINT: 2, SIGQUIT: 3, SIGILL: 4, SIGFPE: 8, SIGKILL: 9, SIGSEGV: 11, SIGTERM: 15, SIGBREAK: 21, SIGABRT: 22, SIGWINCH: 28 };

const map = /#define UV_ERRNO_MAP\(XX\)((?:.*\\\n)+.*\n)/.exec(uvH);
if (map === null) throw new Error("uv.h: no UV_ERRNO_MAP");
const ERRNOS = [...map[1].matchAll(/XX\((\w+), "([^"]*)"\)/g)].map((m) => [m[1], m[2]]);
if (ERRNOS.length < 80) throw new Error(`uv.h: only ${ERRNOS.length} errno entries`);
for (const [n] of ERRNOS) if (!new RegExp(`#\\s*define UV__${n}\\b`).test(errnoH)) throw new Error(`uv/errno.h: no UV__${n}`);

const banner = (c) => `${c} GENERATED by scripts/gen-os-names.mjs from Node ${process.version}'s libuv headers — do not edit;
${c === "//" ? "//" : " *"} --check requires byte-identity. SEMANTICS.md S118.`;

const ts = `${banner("//")}
//
// The names one compiled module shares with every host: the module keeps
// NAMES, the host answers the NUMBER its OS gives each (abi.ts hostNum
// kinds 16 and 17; 0 = this OS has no such name).

/** Node's os.constants.signals keys over every OS, node_constants.cc's
 * order (a number reads back as the FIRST name its OS gives it). */
export const SIGNAL_NAMES: readonly string[] = [
${SIGNALS.map((s) => `  "${s}",`).join("\n")}
];

/** libuv's UV_ERRNO_MAP, in its order: [name, message] — the names and
 * texts util.getSystemErrorMap() answers on every OS. */
export const ERRNO_NAMES: readonly (readonly [string, string])[] = [
${ERRNOS.map(([n, m]) => `  ["${n}", ${JSON.stringify(m)}],`).join("\n")}
];

/** The index of a signal / errno name (a generator-time constant). */
export function signalIndex(name: string): number {
  const i = SIGNAL_NAMES.indexOf(name);
  if (i < 0) throw new Error(\`os-names: no signal \${name}\`);
  return i;
}
export function errnoIndex(name: string): number {
  const i = ERRNO_NAMES.findIndex(([n]) => n === name);
  if (i < 0) throw new Error(\`os-names: no errno \${name}\`);
  return i;
}
`;

const h = `/*${banner("")}
 *
 * The native hosts' answers to abi.ts hostNum kinds 16 (a signal's number)
 * and 17 (an errno's libuv number), index for index with
 * backend/wasm/os-names.ts. 0 = this OS has no such name. */
#ifndef WN_OS_NAMES_H
#define WN_OS_NAMES_H

#include <errno.h>
#include <signal.h>
#include <stdint.h>

#include "uv_errno.h"

#define WN_NSIGNALS ${SIGNALS.length}
#define WN_NERRNOS ${ERRNOS.length}

/* a signal: node_constants.cc's rule (the name where <signal.h> defines
 * it); Windows: the MSVC + uv/win.h set Node is built with */
static const int32_t wn_signal_numbers[WN_NSIGNALS] = {
#if defined(_WIN32)
${SIGNALS.map((s) => `    ${WIN32_SIGNALS[s] ?? 0}, /* ${s} */`).join("\n")}
#else
${SIGNALS.map((s) => `#ifdef ${s}\n    ${s},\n#else\n    0,\n#endif`).join("\n")}
#endif
};

/* an errno: libuv's number for it (uv_errno.h) */
static const int32_t wn_errno_numbers[WN_NERRNOS] = {
${ERRNOS.map(([n]) => `    UV__${n},`).join("\n")}
};

#endif
`;

const uvErrno = `/* VENDORED from libuv (Node ${process.version}'s include/node/uv/errno.h) by
 * scripts/gen-os-names.mjs — do not edit; wn_os_names.h's errno numbers. */
${errnoH}`;

const outs = [
  [join(root, "packages/compiler/src/backend/wasm/os-names.ts"), ts],
  [join(root, "packages/runtime/src/wasmnative/wn_os_names.h"), h],
  [join(root, "packages/runtime/src/wasmnative/uv_errno.h"), uvErrno],
];
let stale = false;
for (const [p, text] of outs) {
  if (check) {
    let have = "";
    try {
      have = readFileSync(p, "utf8");
    } catch {
      // missing
    }
    if (have !== text) {
      console.error(`stale: ${p} (re-run scripts/gen-os-names.mjs with the oracle Node)`);
      stale = true;
    }
  } else {
    writeFileSync(p, text);
    console.log(`wrote ${p}`);
  }
}
if (stale) process.exit(1);
if (check) console.log(`ok: ${SIGNALS.length} signals, ${ERRNOS.length} errnos`);
