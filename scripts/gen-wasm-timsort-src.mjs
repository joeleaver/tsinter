#!/usr/bin/env node
/* Renders packages/compiler/src/backend/wasm/timsort-src.ts from
 * packages/runtime/vendor/quickjs-ng/tsinter_timsort.h, the one text of V8's sort:
 * clang compiles the header into the QuickJS engine, and the WasmGC tier's C-subset
 * compiler compiles the rendered string into a program's module. Run it after editing
 * the header (packages/compiler/test/wasm-sort.test.ts goes red otherwise), then rebuild
 * the engine (scripts/build-engine-wasm.mjs). */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(import.meta.dirname, "..");
export const HEADER_PATH = join(root, "packages/runtime/vendor/quickjs-ng/tsinter_timsort.h");
export const OUT_PATH = join(root, "packages/compiler/src/backend/wasm/timsort-src.ts");

export function renderTimsortSrc(header) {
  if (header.includes("`") || header.includes("${")) throw new Error("the header holds a template-literal metacharacter");
  return (
    "/* GENERATED by scripts/gen-wasm-timsort-src.mjs from\n" +
    " * packages/runtime/vendor/quickjs-ng/tsinter_timsort.h — do not edit. */\n" +
    "export const TIMSORT_C = String.raw`" +
    header +
    "`;\n"
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT_PATH, renderTimsortSrc(readFileSync(HEADER_PATH, "utf8")));
}
