// Regenerates packages/compiler/src/backend/wasm/ryu-tables.ts from the
// vendored Ryū full table header. Run from the repo root:
//   node scripts/gen-wasm-ryu-tables.mjs
// The output is checked in: the tables are static data the wasm emitter
// embeds into modules, and generating at build time would couple the
// compiler package to the runtime package's vendor tree.
import { readFileSync, writeFileSync } from "node:fs";

const header = readFileSync("packages/runtime/vendor/ryu/d2s_full_table.h", "utf8");

function extract(name, expected) {
  const start = header.indexOf(`${name}[`);
  if (start < 0) throw new Error(`${name} not found`);
  const open = header.indexOf("{", start);
  const close = header.indexOf("};", open);
  const body = header.slice(open + 1, close);
  const pairs = [...body.matchAll(/\{\s*(\d+)u\s*,\s*(\d+)u\s*\}/g)].map((m) => [BigInt(m[1]), BigInt(m[2])]);
  if (pairs.length !== expected) throw new Error(`${name}: ${pairs.length} pairs, expected ${expected}`);
  return pairs;
}

const inv = extract("DOUBLE_POW5_INV_SPLIT", 342);
const pow = extract("DOUBLE_POW5_SPLIT", 326);

function lines(pairs) {
  return pairs.map(([lo, hi]) => `  ${lo}n, ${hi}n,`).join("\n");
}

writeFileSync(
  "packages/compiler/src/backend/wasm/ryu-tables.ts",
  `/* GENERATED by scripts/gen-wasm-ryu-tables.mjs — do not edit.
 *
 * Ryū's 128-bit power-of-five tables (Ulf Adams, Apache-2.0/Boost-1.0 —
 * see packages/runtime/vendor/ryu/), flattened to interleaved (lo, hi)
 * u64 pairs exactly as the emitter's d2d port indexes them: entry q is
 * (table[2q], table[2q+1]). The wasm lane embeds them as passive data
 * segments; the C lane includes the same header directly — one source of
 * truth, two encodings.
 */

export const DOUBLE_POW5_INV_BITCOUNT = 125;
export const DOUBLE_POW5_BITCOUNT = 125;

/** 342 entries — the inverse powers, e2 >= 0 side. */
export const DOUBLE_POW5_INV_SPLIT: readonly bigint[] = [
${lines(inv)}
];

/** 326 entries — the powers, e2 < 0 side. */
export const DOUBLE_POW5_SPLIT: readonly bigint[] = [
${lines(pow)}
];
`,
);
console.log(`wrote ryu-tables.ts: ${inv.length} inv + ${pow.length} pow entries`);
