// Regenerates packages/compiler/src/backend/wasm/ieee754-src.ts from the
// vendored V8 file packages/runtime/vendor/v8-ieee754/src/base/ieee754.cc.
// Run from the repo root:
//   node scripts/gen-wasm-ieee754-src.mjs
// The output is checked in (the gen-wasm-casing-tables.mjs rationale: the
// compiler package must not read the runtime package's vendor tree at build
// or run time). ieee754.cc exists ONCE in the repository -- the vendored copy,
// which the native lanes compile as C++ (packages/runtime/src/scr_ieee754.cc)
// -- and the wasm tier's text is this generator's output over it. The drift
// test (packages/compiler/test/wasm-ieee754-src-drift.test.ts) imports
// `renderIeee754Src` from here, renders the SAME vendored file, and requires
// the checked-in ieee754-src.ts byte for byte, plus the vendored file's
// pinned sha256 -- so the two lanes cannot compute from different texts.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

export const VENDORED_PATH = "packages/runtime/vendor/v8-ieee754/src/base/ieee754.cc";
export const OUT_PATH = "packages/compiler/src/backend/wasm/ieee754-src.ts";
/** V8 13.6.233.17's src/base/ieee754.cc (Node v24.18.1's V8), as vendored. */
export const VENDORED_SHA256 = "1bf999809d4c4c1d31ad5ff3578d32614796f159e08b9e7782560d017721a0c2";

/** The checked-in ieee754-src.ts for the vendored text `cc`. Two edits, both
 * outside any code the wasm tier compiles: `namespace legacy` (the pre-2019
 * pow, which Math.pow no longer calls -- Math.pow is `**`, SEMANTICS.md S079)
 * becomes one comment line naming the lines it stood on, and the one backtick
 * (inside a comment) is spelled through a template substitution so the
 * String.raw literal can hold it. */
export function renderIeee754Src(cc) {
  const sha = createHash("sha256").update(cc).digest("hex");
  if (sha !== VENDORED_SHA256) {
    throw new Error(`${VENDORED_PATH}: sha256 ${sha}, expected ${VENDORED_SHA256} (update the pin with the vendored file)`);
  }
  const lines = cc.split("\n");
  const first = lines.indexOf("namespace legacy {");
  const last = lines.indexOf("}  // namespace legacy");
  if (first < 0 || last < first) throw new Error("ieee754.cc: namespace legacy not found");
  const kept = [
    ...lines.slice(0, first),
    `/* [tsinter] upstream lines ${first + 1}-${last + 1} (namespace legacy: the pre-2019 pow) omitted */`,
    ...lines.slice(last + 1),
  ].join("\n");
  if (kept.includes("${")) throw new Error("ieee754.cc: a `${` would break the template literal");
  const body = kept.replace(/`/g, '${"`"}');
  return `/* GENERATED by scripts/gen-wasm-ieee754-src.mjs from ${VENDORED_PATH} -- do not edit by hand.
 *
 * V8's src/base/ieee754.cc, the C++ source of Math's transcendental functions in
 * Node v24.18.1 (V8 13.6.233.17-node.50; upstream tag 13.6.233.17,
 * https://chromium.googlesource.com/v8/v8/+/refs/tags/13.6.233.17/src/base/ieee754.cc,
 * sha256 ${VENDORED_SHA256}). The file is vendored ONCE, under
 * packages/runtime/vendor/v8-ieee754/, and every lane computes from it: the native
 * lanes compile it as C++ (packages/runtime/src/scr_ieee754.cc), and ieee754.ts
 * compiles THIS text -- the vendored file with the two edits the generator makes --
 * to WebAssembly with the C-subset compiler in csubset.ts (SEMANTICS.md S100). The
 * edits, both outside any code: upstream lines ${first + 1}-${last + 1} (\`namespace legacy\`,
 * the pre-2019 pow, which Math.pow no longer calls -- Math.pow is \`**\`, SEMANTICS.md
 * S079) are replaced by the one comment line that marks them, and the backtick inside
 * a comment is spelled through a template substitution so this literal can hold it.
 * test/wasm-ieee754-src-drift.test.ts re-renders the vendored file and requires this
 * one byte for byte.
 *
 * Upstream notice (reproduced in full in the text below):
 *   Copyright (C) 1993 by Sun Microsystems, Inc. All rights reserved.
 *   Developed at SunSoft, a Sun Microsystems, Inc. business. Permission to use,
 *   copy, modify, and distribute this software is freely granted, provided that
 *   this notice is preserved.
 *   Copyright 2016 the V8 project authors. All rights reserved (BSD-style license).
 */

export const IEEE754_CC = String.raw\`
${body}\`;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(OUT_PATH, renderIeee754Src(readFileSync(VENDORED_PATH, "utf8")));
  console.log(`wrote ${OUT_PATH}`);
}
