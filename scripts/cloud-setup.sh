#!/usr/bin/env bash
# Reproduce tsinter's test toolchain in a fresh cloud session (Ubuntu 24.04,
# x86_64, Claude Code on the web). Run from the repo root:
#
#   bash scripts/cloud-setup.sh            # Node + pnpm deps + build + clang 21
#   source "${TSINTER_TOOLS:-/opt/tsinter-tools}/env.sh"   # then, in every shell
#
# What it installs, and why each source (see docs/cloud-env-probe.md):
#   - Node v24.18.1 (the oracle) from the nodejs.org tarball, checked against
#     SHASUMS256.txt. The image's own node (v22) and /opt/node24 (v24.22.1) are
#     the wrong versions, so PATH must put this one first.
#   - pnpm 10 through corepack, then `pnpm install --frozen-lockfile` + build.
#   - clang 21.1.8 from the official LLVM GitHub release tarball. apt.llvm.org
#     is blocked by the session's egress proxy (403) and Ubuntu noble only ships
#     clang <= 20. The tarball's SHA256 is pinned below and also checked against
#     the digest in the release's sigstore attestation (.jsonl). The signature
#     itself is not verified (no cosign in the image).
#   - Optionally (SURVEY=1) @types/node + undici-types into the survey cache,
#     which tests/real-apps-round3/survey/plan.mjs expects at
#     $SURVEY_CACHE/node-types/node_modules. Tarballs only, no install scripts.
#
# Idempotent: finished steps are skipped. Needs ~2 GB download and ~3 GB disk
# for LLVM. SKIP_CLANG=1 skips clang (the wasm lane and census do not need it).
set -euo pipefail

NODE_VERSION=v24.18.1
LLVM_VERSION=21.1.8
LLVM_SHA256=b3b7f2801d15d50736acea3c73982994d025b01c2f035b91ae3b49d1b575732b
TOOLS=${TSINTER_TOOLS:-/opt/tsinter-tools}
DL=${TSINTER_DL:-$TOOLS/downloads}
REPO=$(cd "$(dirname "$0")/.." && pwd)

mkdir -p "$TOOLS" "$DL"
log() { printf '\n== %s\n' "$*"; }

# --- Node -------------------------------------------------------------------
NODE_DIR=$TOOLS/node-$NODE_VERSION-linux-x64
if [ ! -x "$NODE_DIR/bin/node" ]; then
  log "Node $NODE_VERSION"
  tarball=node-$NODE_VERSION-linux-x64.tar.xz
  curl -fsSL -o "$DL/SHASUMS256.txt" "https://nodejs.org/dist/$NODE_VERSION/SHASUMS256.txt"
  curl -fsSL -o "$DL/$tarball" "https://nodejs.org/dist/$NODE_VERSION/$tarball"
  (cd "$DL" && grep " $tarball\$" SHASUMS256.txt | sha256sum -c -)
  tar -xJf "$DL/$tarball" -C "$TOOLS"
fi
export PATH=$NODE_DIR/bin:$PATH
hash -r
[ "$(node -v)" = "$NODE_VERSION" ] || { echo "node on PATH is $(node -v), want $NODE_VERSION" >&2; exit 1; }
export COREPACK_ENABLE_DOWNLOAD_PROMPT=0

# --- clang 21 ---------------------------------------------------------------
LLVM_DIR=$TOOLS/llvm-$LLVM_VERSION
if [ "${SKIP_CLANG:-0}" != 1 ] && [ ! -x "$LLVM_DIR/bin/clang" ]; then
  log "clang $LLVM_VERSION"
  f=LLVM-$LLVM_VERSION-Linux-X64.tar.xz
  base=https://github.com/llvm/llvm-project/releases/download/llvmorg-$LLVM_VERSION
  if ! echo "$LLVM_SHA256  $DL/$f" | sha256sum -c --status - 2>/dev/null; then
    curl -fsSL -o "$DL/$f" "$base/$f"
  fi
  echo "$LLVM_SHA256  $DL/$f" | sha256sum -c -
  curl -fsSL -o "$DL/$f.jsonl" "$base/$f.jsonl"
  attested=$(node -e '
    const b = JSON.parse(require("fs").readFileSync(process.argv[1], "utf8"));
    const p = JSON.parse(Buffer.from(b.dsseEnvelope.payload, "base64").toString());
    process.stdout.write(p.subject.find((s) => s.name === process.argv[2]).digest.sha256);
  ' "$DL/$f.jsonl" "$f")
  [ "$attested" = "$LLVM_SHA256" ] || { echo "attestation digest $attested != pinned $LLVM_SHA256" >&2; exit 1; }
  mkdir -p "$LLVM_DIR.tmp"
  # Only what the wasm-native lane uses: the clang driver, lld, llvm-ar,
  # the symbolizer (sanitizer reports) and the clang resource dir.
  tar -xJf "$DL/$f" -C "$LLVM_DIR.tmp" --strip-components=1 --wildcards \
    '*/bin/clang*' '*/bin/lld' '*/bin/ld.lld' '*/bin/llvm-ar' '*/bin/llvm-symbolizer' '*/lib/clang/*'
  mv "$LLVM_DIR.tmp" "$LLVM_DIR"
  [ "${KEEP_DOWNLOADS:-0}" = 1 ] || rm -f "$DL/$f"
fi
if [ -x "$LLVM_DIR/bin/clang" ]; then
  export PATH=$LLVM_DIR/bin:$PATH
  hash -r
fi

# --- env file ---------------------------------------------------------------
cat >"$TOOLS/env.sh" <<EOF
# Generated by scripts/cloud-setup.sh
export PATH=$( [ -x "$LLVM_DIR/bin/clang" ] && printf '%s:' "$LLVM_DIR/bin" )$NODE_DIR/bin:\$PATH
export COREPACK_ENABLE_DOWNLOAD_PROMPT=0
export SURVEY_MEMMAX=0   # no systemd user bus in the container: survey workers run uncapped
hash -r
EOF

# --- workspace --------------------------------------------------------------
log "pnpm install + build"
cd "$REPO"
corepack pnpm@10 install --frozen-lockfile
corepack pnpm@10 build

# --- survey prerequisite (optional) ------------------------------------------
if [ "${SURVEY:-0}" = 1 ]; then
  log "survey: @types/node into \$SURVEY_CACHE/node-types"
  node --input-type=module -e '
    import { join } from "node:path";
    const lib = await import(process.argv[1]);
    const tree = join(lib.ROOT, "node-types");
    lib.mkdirSync(tree, { recursive: true });
    const { manifest } = await lib.installClosure(tree, [{ name: "@types/node", range: "24.13.3" }]);
    console.log(manifest.map((m) => `${m.name}@${m.version}`).join(" "));
  ' "$REPO/tests/real-apps-round3/survey/lib.mjs"
fi

log "versions"
node -v
corepack pnpm@10 --version
command -v clang >/dev/null && clang --version | head -1
echo "now: source $TOOLS/env.sh"
