// Regenerates packages/compiler/src/backend/wasm/casing-tables.ts from the
// vendored quickjs-ng Unicode case-conversion/property tables. Run from the
// repo root:
//   node scripts/gen-wasm-casing-tables.mjs
// The output is checked in: the tables are static data the wasm emitter
// embeds into modules, and generating at build time would couple the
// compiler package to the runtime package's vendor tree (same rationale as
// gen-wasm-ryu-tables.mjs, which this mirrors).
//
// This file READS packages/runtime/vendor/quickjs-ng/libunicode-table.h at
// generation time (not an embedded/forked copy of its literals) — the
// drift test (packages/compiler/test/wasm-casing-tables-drift.test.ts)
// imports `extractAll` from here, re-parses the SAME live header, and
// byte-compares the result against the checked-in casing-tables.ts, so a
// future vendor bump that changes the header without regenerating trips a
// test instead of silently desynchronizing the two.
import { readFileSync, writeFileSync } from "node:fs";

const HEADER_PATH = "packages/runtime/vendor/quickjs-ng/libunicode-table.h";

function extract(header, name, expected) {
  const start = header.indexOf(`${name}[`);
  if (start < 0) throw new Error(`${name} not found`);
  const open = header.indexOf("{", start);
  const close = header.indexOf("};", open);
  const body = header.slice(open + 1, close);
  const values = [...body.matchAll(/0x[0-9a-fA-F]+/g)].map((m) => Number(m[0]));
  if (values.length !== expected) {
    throw new Error(`${name}: ${values.length} entries, expected ${expected}`);
  }
  return values;
}

/** Re-parses the vendored header (path relative to repo root, or an
 * already-read string via `headerText`) and returns all seven tables in
 * the same shape casing-tables.ts exports. Values are plain JS numbers —
 * `Number("0x...")` on a hex literal parses the unsigned magnitude
 * directly (JS numbers are IEEE754 doubles, not 32-bit ints), so entries
 * with the top bit set (case_conv_table1 has several, e.g. 0xb75d9901)
 * come through as ordinary positive numbers, never sign-flipped — that
 * hazard is a 32-bit-bitwise-op concern (`|0`, `<<`), which this function
 * never applies to the raw values. */
export function extractAll(headerText) {
  const header = headerText ?? readFileSync(HEADER_PATH, "utf8");
  return {
    table1: extract(header, "case_conv_table1", 378),
    table2: extract(header, "case_conv_table2", 378),
    ext: extract(header, "case_conv_ext", 58),
    casedTable: extract(header, "unicode_prop_Cased1_table", 190),
    casedIndex: extract(header, "unicode_prop_Cased1_index", 18),
    ciTable: extract(header, "unicode_prop_Case_Ignorable_table", 785),
    ciIndex: extract(header, "unicode_prop_Case_Ignorable_index", 75),
  };
}

function lines(values, perLine) {
  const rows = [];
  for (let i = 0; i < values.length; i += perLine) {
    rows.push("  " + values.slice(i, i + perLine).map((v) => `0x${v.toString(16)}`).join(", ") + ",");
  }
  return rows.join("\n");
}

function regenerate() {
  const { table1, table2, ext, casedTable, casedIndex, ciTable, ciIndex } = extractAll();
  writeFileSync(
    "packages/compiler/src/backend/wasm/casing-tables.ts",
    `/* GENERATED by scripts/gen-wasm-casing-tables.mjs — do not edit by hand.
 * Source: ${HEADER_PATH}
 * Regenerate: node scripts/gen-wasm-casing-tables.mjs
 * Drift check: packages/compiler/test/wasm-casing-tables-drift.test.ts
 *   (re-parses the live vendored header and byte-compares against this
 *   file — catches a vendor bump that lands without regeneration)
 *
 * ECMA-262 Default Case Conversion tables, vendored from quickjs-ng's
 * libunicode-table.h (packages/runtime/vendor/quickjs-ng/) — the same
 * tables the C lane links against for toLowerCase/toUpperCase
 * (scr_regex.c's scr_str_case_conv). One source of truth, two encodings:
 * the C lane includes the header directly, the wasm lane embeds these as
 * passive data segments (casing.ts). Measured against Node v24.18.1
 * (ICU 78.3 / Unicode 17.0) at zero skew — see
 * increment-20-design.md / inc20/rev-preread.md for the sweep.
 *
 * All values fit u32 and are plain JS numbers (unlike ryu-tables.ts's u64
 * pairs, which need bigint) — every table here is u32 or narrower.
 */

/** 378 entries × u32 — case_conv_table1: packed (code:17, len:7, type:4,
 * data_hi:4) range-table entries, binary-searched by code point. */
export const CASE_CONV_TABLE1: readonly number[] = [
${lines(table1, 4)}
];

/** 378 entries × u8 — case_conv_table2: the data_lo byte paired with each
 * case_conv_table1 entry by index. */
export const CASE_CONV_TABLE2: readonly number[] = [
${lines(table2, 8)}
];

/** 58 entries × u16 — case_conv_ext: the extension code-point pool the
 * EXT/EXT2/EXT3/D1_EXT run types index into. */
export const CASE_CONV_EXT: readonly number[] = [
${lines(ext, 8)}
];

/** 190 entries × u8 — unicode_prop_Cased1_table: the compressed-RLE
 * bitmap body for the Cased property (lre_is_cased's table fallback). */
export const UNICODE_PROP_CASED1_TABLE: readonly number[] = [
${lines(casedTable, 8)}
];

/** 18 entries × u8 — unicode_prop_Cased1_index: the 3-byte-packed block
 * index over the table above. */
export const UNICODE_PROP_CASED1_INDEX: readonly number[] = [
${lines(casedIndex, 8)}
];

/** 785 entries × u8 — unicode_prop_Case_Ignorable_table: the compressed-
 * RLE bitmap body for the Case_Ignorable property. */
export const UNICODE_PROP_CASE_IGNORABLE_TABLE: readonly number[] = [
${lines(ciTable, 8)}
];

/** 75 entries × u8 — unicode_prop_Case_Ignorable_index: the 3-byte-packed
 * block index over the table above. */
export const UNICODE_PROP_CASE_IGNORABLE_INDEX: readonly number[] = [
${lines(ciIndex, 8)}
];
`,
  );
  console.log(
    `wrote casing-tables.ts: table1=${table1.length} table2=${table2.length} ext=${ext.length} ` +
      `casedTable=${casedTable.length} casedIndex=${casedIndex.length} ciTable=${ciTable.length} ciIndex=${ciIndex.length}`,
  );
}

// Only regenerate when run directly (`node scripts/gen-wasm-casing-tables.mjs`)
// — importing `extractAll` for the drift test must not have the side
// effect of rewriting casing-tables.ts.
if (import.meta.url === `file://${process.argv[1]}`) {
  regenerate();
}
