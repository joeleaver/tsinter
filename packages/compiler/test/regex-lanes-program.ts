/* The shared regex table's program (native-regex-lanes.test.ts): one
 * TypeScript program, compiled for every lane and run by Node, that walks
 * a table of (pattern, flags) rows and prints, per row, what `new RegExp`
 * does — the value's .source and .flags, V8's SyntaxError text, or the
 * fence's named Error with its `code` — and, for the rows marked for the
 * exec sweep, what the common regex surface returns over a set of
 * subjects: search, test, match, replace (with a template exercising every
 * GetSubstitution form), matchAll (each match's index and slice) and
 * split. Every lane's output must equal Node's line for line. */

/** A table row: pattern and flags as hex UTF-16 code units, then "1" when
 * the row is in the exec sweep. Rows are newline-separated; fields
 * tab-separated. */
export function renderRow(pattern: string, flags: string, sweep: boolean): string {
  const hex = (s: string): string => Array.from({ length: s.length }, (_, i) => s.charCodeAt(i).toString(16).padStart(4, "0")).join("");
  return `${hex(pattern)}\t${hex(flags)}\t${sweep ? "1" : "0"}`;
}

/** The program's source over the rendered table text. */
export function regexLanesProgram(table: string, subjects: readonly string[]): string {
  return `// GENERATED by native-regex-lanes.test.ts
const TABLE: string = ${JSON.stringify(table)};
const SUBJECTS: string[] = ${JSON.stringify(subjects)};
const TEMPLATE: string = "[$&|$1|$2|$<n>|$\`|$'|$$]";

// A pair is decoded as one code point: the native lanes' strings cannot
// hold a half on its own, even for a moment.
function dec(h: string): string {
  let s = "";
  for (let i = 0; i < h.length; i += 4) {
    const u = parseInt(h.slice(i, i + 4), 16);
    const v = i + 4 < h.length ? parseInt(h.slice(i + 4, i + 8), 16) : 0;
    if (u >= 0xd800 && u <= 0xdbff && v >= 0xdc00 && v <= 0xdfff) {
      s += String.fromCharCode(u, v);
      i += 4;
    } else s += String.fromCharCode(u);
  }
  return s;
}

/** A slice as text, or — for a subject holding surrogates, where a slice
 * can split a pair and the native lanes' UTF-8 strings cannot hold the
 * lone half (their registered string representation, not a regex
 * difference) — as its length in code units. */
function show(x: string | undefined, astral: boolean): string {
  const v = x ?? "";
  return astral ? String(v.length) : JSON.stringify(v);
}

function sweep(i: number, re: RegExp): void {
  const src = re.source;
  let base = "";
  for (const c of re.flags) if (c !== "g" && c !== "y") base += c;
  const one = new RegExp(src, base);
  const all = new RegExp(src, base + "g");
  for (let k = 0; k < SUBJECTS.length; k++) {
    const s = SUBJECTS[k]!;
    let astral = false;
    for (let j = 0; j < s.length; j++) if (s.charCodeAt(j) >= 0xd800 && s.charCodeAt(j) <= 0xdfff) astral = true;
    let line = i + "." + k + " search " + s.search(re) + " test " + one.test(s);
    const m = s.match(one);
    let ms = "";
    if (m !== null) for (const x of m) ms += show(x, astral) + ",";
    line += " match " + (m === null ? "null" : ms);
    // replace without /g on the flag-free twin: a sticky non-global
    // regex VALUE carries lastIndex state no lane models (SEMANTICS.md
    // S003), not what this table measures; /gy is stateless per call
    line += " replace " + show(s.replace(one, TEMPLATE), astral);
    line += " replaceAll " + show(s.replace(all, TEMPLATE), astral);
    if (re.flags.indexOf("y") >= 0) line += " replaceGy " + show(s.replace(new RegExp(src, base + "gy"), TEMPLATE), astral);
    let ma = "";
    for (const mm of s.matchAll(all)) {
      ma += mm.index + ":";
      for (const x of mm) ma += show(x, astral) + ",";
      ma += ";";
    }
    line += " matchAll " + ma;
    console.log(line);
  }
}

const rows = TABLE.split("\\n");
for (let i = 0; i < rows.length; i++) {
  const f3 = rows[i]!.split("\\t");
  const p = dec(f3[0]!);
  const f = dec(f3[1]!);
  try {
    const re = new RegExp(p, f);
    console.log(i + " ok " + JSON.stringify(re.source) + " " + re.flags);
    if (f3[2] === "1") sweep(i, re);
  } catch (e) {
    const err = e as NodeJS.ErrnoException;
    console.log(i + " " + err.name + " " + JSON.stringify(err.message) + " " + (err.code ?? "-"));
  }
}
`;
}
