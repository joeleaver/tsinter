// Generates packages/compiler/src/frontend/stub-builtin-exports.ts: for every
// builtin whose bindings are stubs (SEMANTICS.md S129), the names its ES
// module namespace exports in THIS Node, without flags — the set a named
// import is linked against (a name outside it is Node's link-time
// SyntaxError). Run it under the oracle, Node v24.18.1:
// usage: node packages/compiler/test/gen-stub-builtin-exports.mjs packages/compiler/src/frontend/shared.ts packages/compiler/src/frontend/stub-builtin-exports.ts
import { readFileSync, writeFileSync } from "node:fs";
import { builtinModules } from "node:module";

const [sharedPath, outPath] = process.argv.slice(2);
if (process.version !== "v24.18.1") throw new Error(`run under Node v24.18.1 (the oracle), not ${process.version}`);
const shared = readFileSync(sharedPath, "utf8");
const listOf = (re) => {
  const m = re.exec(shared);
  if (m === null) throw new Error(`no match for ${re}`);
  return [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]);
};
const supported = new Set(listOf(/export const SUPPORTED_BUILTIN_MODULES = \[([^\]]*)\]/));
const observable = new Set(listOf(/const IMPORT_OBSERVABLE_BUILTINS: ReadonlySet<string> = new Set\(\[([^\]]*)\]\)/));
const mods = [...new Set(builtinModules.map((m) => m.replace(/^node:/, "")))]
  .filter((m) => !supported.has(m) && !observable.has(m))
  .sort();
const table = {};
for (const m of mods) {
  const ns = await import(`node:${m}`);
  table[m] = Object.keys(ns).sort();
}
const lines = Object.entries(table).map(([m, names]) => `  ${JSON.stringify(m)}: ${JSON.stringify(names)},`);
writeFileSync(
  outPath,
  `/* GENERATED by packages/compiler/test/gen-stub-builtin-exports.mjs under Node ${process.version} — do not edit.
 * The ES module export names of each stub builtin (SEMANTICS.md S129): a
 * named import outside its set is Node's link-time SyntaxError. */
export const STUB_BUILTIN_EXPORTS: Readonly<Record<string, readonly string[]>> = {
${lines.join("\n")}
};
`,
);
console.log(`${mods.length} modules`);
