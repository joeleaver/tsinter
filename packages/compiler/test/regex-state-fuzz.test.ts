/* Board #301: the stateful regex surface, fuzzed against Node on every lane.
 *
 * A seeded generator writes ONE program: per row, a regex LITERAL (so a
 * function replacer's parameters are positional at compile time), a
 * subject, and a random sequence of operations over the SAME regex object —
 * test, exec (with the result's .index/.input companions), match (the
 * every-match form when global), matchAll (from the regex's lastIndex),
 * search, replace/replaceAll with templates and with FUNCTION replacers
 * (regex and string patterns),
 * split with and without a limit, and lastIndex reads and writes (fractions,
 * negatives, NaN, past the end). The function replacers run regexes
 * themselves — a shared global regex whose lastIndex carries across calls,
 * the outer regex's own lastIndex, a nested replace — which is what the
 * matcher's re-entrancy rests on (backend/wasm/regex-state.ts: the replacer
 * runs only after every match is collected).
 *
 * Required: wasm, c and llvm print exactly Node's output. The printing
 * steers clear of the registered divergences the rows are not about: a
 * capture that did not participate in an exec/match ROW prints through
 * `?? ""` (S064 — "" on this tier, undefined in Node; replacers get
 * Node's exact undefined and print it), and on a subject holding astral
 * characters slices print as lengths (the native lanes' strings cannot hold
 * a lone surrogate — S002's native arm).
 *
 * REGEX_STATE_ROWS / REGEX_STATE_SEED widen or move the sweep;
 * SCRIPTC_SAN=1 builds the native lanes with ASan + the RC audit. */
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, test } from "vitest";
import { compile } from "../src/index.js";
import { runWasm } from "./wasm-host.js";

const SAN = process.env["SCRIPTC_SAN"] === "1";

/** mulberry32 */
function rng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** [pattern source as written in a literal, capture count (whole match
 * included), named groups] */
const PATTERNS: [string, number, string[]][] = [
  ["a", 1, []],
  ["ab", 1, []],
  ["a*", 1, []],
  ["a|b", 1, []],
  ["(a)(b)?", 3, []],
  ["(\\d+)", 2, []],
  ["(?<y>\\d{2})(?<m>\\d{2})?", 3, ["y", "m"]],
  ["\\b", 1, []],
  ["(?:)", 1, []],
  ["x*", 1, []],
  ["(a)|(b)", 3, []],
  [".", 1, []],
  ["\\w+", 1, []],
  ["(\\w)(\\w)?", 3, []],
  ["[aeiou]", 1, []],
  ["^", 1, []],
  ["$", 1, []],
  ["(?=a)", 1, []],
  ["a(?!b)", 1, []],
  ["\u{1F600}", 1, []],
  ["(.)\\1", 2, []],
  ["\\s*", 1, []],
  ["(?<w>[a-z])", 2, ["w"]],
];

const SUBJECTS = ["", "a", "ab", "aab ab", "abab", "ba", "a1 22 333", "202401 2025", "a\u{1F600}b\u{1F600}", "xyz", "aaaa", "hello world", "aa\nab"];

const TEMPLATES = ["[$&]", "$1-$2", "$<y>|$<w>", "$`|$'", "$$", "x", "<$0$10$01>"];

const LAST_INDEX = ["0", "1", "2", "3", "-1", "2.5", "100", "NaN", "4"];

function genProgram(rows: number, seed: number): string {
  const r = rng(seed);
  const pick = <T>(xs: readonly T[]): T => xs[Math.floor(r() * xs.length)]!;
  const out: string[] = [];
  out.push("// GENERATED by regex-state-fuzz.test.ts");
  out.push("function astralIn(s: string): boolean { for (let i = 0; i < s.length; i++) { const c = s.charCodeAt(i); if (c >= 0xd800 && c <= 0xdfff) return true; } return false; }");
  out.push("let ASTRAL = false;");
  out.push("function v(x: string | undefined): string { const s = x ?? \"\"; return ASTRAL ? `#${s.length}` : JSON.stringify(s); }");
  out.push("function vs(xs: string[] | null): string { if (xs === null) return \"null\"; let o = \"\"; for (const x of xs) o += v(x) + \",\"; return `[${o}]`; }");
  out.push("const inner = /[ab]/g;");
  out.push("function line(id: number, k: number, what: string, text: string): void { console.log(`${id}.${k} ${what} ${text}`); }");
  const calls: string[] = [];
  for (let id = 0; id < rows; id++) {
    const [pat, count, groups] = pick(PATTERNS);
    let flags = "";
    for (const f of "gimsy") if (r() < (f === "g" ? 0.6 : f === "y" ? 0.3 : 0.15)) flags += f;
    if (r() < 0.2 && !flags.includes("i")) flags += "u";
    const subj = pick(SUBJECTS);
    const b: string[] = [];
    b.push(`function r${id}(): void {`);
    b.push(`  const R = /${pat}/${flags};`);
    b.push(`  const S = ${JSON.stringify(subj)};`);
    b.push("  ASTRAL = astralIn(S);");
    const nops = 2 + Math.floor(r() * 6);
    for (let k = 0; k < nops; k++) {
      const op = pick(["test", "exec", "match", "matchAll", "search", "replaceT", "replaceAllT", "replaceF", "replaceAllF", "strReplace", "split", "setLI", "setLI", "li", "test", "exec"]);
      const L = (what: string, expr: string): string => `  line(${id}, ${k}, ${JSON.stringify(what)}, ${expr});`;
      const tryWrap = (body: string): string =>
        `  try {\n${body}\n  } catch (e) { line(${id}, ${k}, "threw", (e as Error).name + ": " + (e as Error).message); }`;
      switch (op) {
        case "test":
          b.push(L("test", "`${R.test(S)} ${R.lastIndex}`"));
          break;
        case "exec":
          b.push(`  const m${k} = R.exec(S);`);
          b.push(`  if (m${k} === null) ${L("exec", "`null ${R.lastIndex}`").trim()}`);
          b.push(`  else ${L("exec", `\`\${vs(m${k})} @\${m${k}.index} \${m${k}.input.length} \${R.lastIndex}\``).trim()}`);
          break;
        case "match":
          b.push(L("match", "`${vs(S.match(R))} ${R.lastIndex}`"));
          break;
        case "matchAll":
          b.push(tryWrap(`    let o = ""; for (const x of S.matchAll(R)) o += x.index + ":" + vs(x) + ";";\n  ${L("matchAll", "`${o} ${R.lastIndex}`")}`));
          break;
        case "search":
          b.push(L("search", "`${S.search(R)} ${R.lastIndex}`"));
          break;
        case "replaceT":
          b.push(L("replace", `\`\${v(S.replace(R, ${JSON.stringify(pick(TEMPLATES))}))} \${R.lastIndex}\``));
          break;
        case "replaceAllT":
          b.push(tryWrap(`  ${L("replaceAll", `\`\${v(S.replaceAll(R, ${JSON.stringify(pick(TEMPLATES))}))} \${R.lastIndex}\``)}`));
          break;
        case "replaceF":
        case "replaceAllF": {
          // (m, p1..pn, offset, string[, groups]) — captures typed
          // `string | undefined` so Node's undefined arrives exactly
          // (half the time UNANNOTATED: the lowering binds each capture to
          // string or string | undefined by whether it can fail to take part)
          const bare = groups.length === 0 && r() < 0.5;
          const caps: string[] = [];
          for (let c = 1; c < count; c++) caps.push(bare ? `p${c}` : `p${c}: string | undefined`);
          const params = bare ? ["m", ...caps, "off", "str"] : ["m: string", ...caps, "off: number", "str: string"];
          if (groups.length > 0) params.push("g: { [k: string]: string | undefined }");
          const capText = caps.map((_, c) => `\${p${c + 1} ?? "U"}`).join("/");
          const gText = groups.length > 0 ? groups.map((n) => `\${g.${n} ?? "U"}`).join("+") : "";
          const nested = r() < 0.3 ? `\${m.replace(/[a-z]/g, (q: string) => q.toUpperCase())}` : "";
          const body = `\`<\${m}|${capText}|\${off}|\${str.length}|\${inner.test(m)}\${inner.lastIndex}|\${R.lastIndex}|${gText}${nested}>\``;
          const call = `S.${op === "replaceF" ? "replace" : "replaceAll"}(R, (${params.join(", ")}) => ${body})`;
          b.push(tryWrap(`  ${L(op, `\`\${v(${call})} \${R.lastIndex}\``)}`));
          break;
        }
        case "strReplace": {
          // a STRING pattern: template and function forms, both arities
          const pat = JSON.stringify(pick(["a", "ab", "", "b", "zz", "\u{1F600}"]));
          const all = r() < 0.5 ? "replaceAll" : "replace";
          const rep = r() < 0.5
            ? JSON.stringify(pick(TEMPLATES))
            : "(m: string, off: number, str: string) => `<${m}|${off}|${str.length}|${inner.test(m)}>`";
          b.push(L(`str-${all}`, `v(S.${all}(${pat}, ${rep}))`));
          break;
        }
        case "split": {
          const lim = r() < 0.5 ? "" : `, ${pick(["0", "1", "2", "3", "10"])}`;
          b.push(L("split", `\`\${vs(S.split(R${lim}))} \${R.lastIndex}\``));
          break;
        }
        case "setLI":
          b.push(`  R.lastIndex = ${pick(LAST_INDEX)};`);
          break;
        case "li":
          b.push(L("li", "`${R.lastIndex}`"));
          break;
      }
    }
    b.push("}");
    out.push(b.join("\n"));
    calls.push(`r${id}();`);
  }
  out.push(...calls);
  return out.join("\n") + "\n";
}

describe("board #301: stateful regex methods, every lane = Node", () => {
  test("generated rows: wasm = c = llvm = Node", async () => {
    const rows = Number(process.env["REGEX_STATE_ROWS"] ?? 400);
    const seed = Number(process.env["REGEX_STATE_SEED"] ?? 0x301);
    const dir = mkdtempSync(join(tmpdir(), "tsinter-regex-state-"));
    const entry = join(dir, "regex-state.ts");
    writeFileSync(entry, genProgram(rows, seed));
    if (process.env["REGEX_STATE_DUMP"]) writeFileSync(process.env["REGEX_STATE_DUMP"], genProgram(rows, seed));
    const node = execFileSync(process.execPath, [entry], { maxBuffer: 1 << 30 }).toString();
    const outs: Record<string, string> = {};
    for (const lane of ["wasm", "c", "llvm"] as const) {
      const outPath = join(dir, lane === "wasm" ? "regex-state.wasm" : `regex-state-${lane}`);
      const res = await compile(entry, { outPath, outDir: join(dir, `out-${lane}`), backend: lane, sanitize: lane !== "wasm" && SAN });
      if (!res.ok) throw new Error(`${lane}: ${res.diagnostics.map((d) => `${d.code} ${d.message}`).join("; ")}`);
      outs[lane] = lane === "wasm" ? (await runWasm(res.binaryPath)).stdout : execFileSync(res.binaryPath, { maxBuffer: 1 << 30 }).toString();
    }
    rmSync(dir, { recursive: true, force: true });
    const firstDiff = (a: string, b: string): string | null => {
      if (a === b) return null;
      const x = a.split("\n");
      const y = b.split("\n");
      for (let i = 0; i < Math.max(x.length, y.length); i++) if (x[i] !== y[i]) return `line ${i}:\n  node ${x[i]}\n  lane ${y[i]}`;
      return "differ";
    };
    const lines = node.split("\n").length;
    console.log(`regex state fuzz: ${rows} rows, seed ${seed}, ${lines} output lines`);
    expect(lines).toBeGreaterThan(rows);
    expect(firstDiff(node, outs["wasm"]!)).toBe(null);
    expect(firstDiff(node, outs["c"]!)).toBe(null);
    expect(firstDiff(node, outs["llvm"]!)).toBe(null);
  }, 1_800_000);
});
