/* A WasmGC → C translator for the small, closed instruction subset the
 * regex engine module uses (follow-up unit D, "native regex = wasm").
 *
 * WHY. The WasmGC tier's regex compiler and matcher are wasm functions
 * built by this package (regex-compiler.ts, regex-interpreter.ts); the
 * build time runs them in-process (regex-buildtime.ts). The native lanes
 * need the SAME verdicts, messages, .source/.flags and match results, so
 * instead of a second, hand-written C engine they compile the very same
 * module's functions, translated here into one C file
 * (packages/runtime/src/scr_regex_engine.h, generated by
 * scripts/gen-native-regex-engine.mjs; native-regex-engine-drift.test.ts
 * requires the checked-in file to equal a fresh translation). One source
 * of truth: an edit to the wasm builders changes the native engine too.
 *
 * WHAT. A decoder for the module's sections (types incl. rec groups,
 * functions, globals, exports, passive data, the name section) and a
 * per-function translator: the operand stack is tracked symbolically as C
 * expressions (pure ones fold, everything with an effect is materialized
 * into a fresh temporary, and a pending expression is materialized before
 * any write it reads from — a local, a global, or array memory); control
 * flow lowers to labels and gotos. Anything outside the subset throws, so
 * a builder change that reaches a new instruction fails the generator and
 * the drift test instead of producing wrong C.
 *
 * SEMANTICS kept. i32 arithmetic wraps (unsigned C arithmetic); shifts take
 * the count mod 32; division traps on zero and on INT32_MIN / -1; every
 * array access is bounds- and null-checked and traps as wasm does; GC
 * objects live in one allocation list with a mark-and-sweep collector the
 * host calls at safe points (roots: the module's reference globals), so
 * the translated code allocates exactly as the wasm does and the host
 * frees what is no longer reachable. A trap calls the host's
 * `scr_rx_trap()`. */

type VT = "i32" | "ref";

interface FuncType {
  params: VT[];
  results: VT[];
}

type Comp =
  | { kind: "func"; ft: FuncType }
  | { kind: "array"; elem: "i8" | "i16" | "i32" | "ref" }
  | { kind: "struct"; fields: ("i8" | "i16" | "i32" | "ref")[] };

interface Global {
  t: VT;
  init: string;
}

interface Body {
  locals: VT[];
  code: Uint8Array;
}

interface Module {
  types: Comp[];
  funcTypes: number[];
  globals: Global[];
  exports: Map<number, string>;
  data: Uint8Array[];
  bodies: Body[];
  names: Map<number, string>;
}

class Reader {
  pos = 0;
  constructor(readonly b: Uint8Array) {}
  u8(): number {
    if (this.pos >= this.b.length) throw new Error("wasm2c: unexpected end of input");
    return this.b[this.pos++]!;
  }
  uleb(): number {
    let result = 0;
    let shift = 0;
    for (;;) {
      const byte = this.u8();
      result += (byte & 0x7f) * 2 ** shift;
      shift += 7;
      if ((byte & 0x80) === 0) return result;
    }
  }
  sleb(): number {
    let result = 0n;
    let shift = 0n;
    let byte: number;
    do {
      byte = this.u8();
      result |= BigInt(byte & 0x7f) << shift;
      shift += 7n;
    } while (byte & 0x80);
    if (byte & 0x40) result -= 1n << shift;
    return Number(result);
  }
  bytes(n: number): Uint8Array {
    const out = this.b.subarray(this.pos, this.pos + n);
    if (out.length !== n) throw new Error("wasm2c: unexpected end of input");
    this.pos += n;
    return out;
  }
  name(): string {
    return new TextDecoder().decode(this.bytes(this.uleb()));
  }
}

function readValType(r: Reader): VT {
  const b = r.u8();
  if (b === 0x7f) return "i32";
  if (b === 0x63 || b === 0x64) {
    r.sleb(); // heap type: only concrete type indices reach this module
    return "ref";
  }
  throw new Error(`wasm2c: value type 0x${b.toString(16)} is outside the subset`);
}

function readStorage(r: Reader): "i8" | "i16" | "i32" | "ref" {
  const b = r.b[r.pos]!;
  if (b === 0x78) {
    r.pos++;
    return "i8";
  }
  if (b === 0x77) {
    r.pos++;
    return "i16";
  }
  return readValType(r);
}

function readComp(r: Reader): Comp {
  let form = r.u8();
  if (form === 0x50 || form === 0x4f) {
    const n = r.uleb();
    for (let i = 0; i < n; i++) r.uleb();
    form = r.u8();
  }
  if (form === 0x60) {
    const params: VT[] = [];
    for (let n = r.uleb(); n > 0; n--) params.push(readValType(r));
    const results: VT[] = [];
    for (let n = r.uleb(); n > 0; n--) results.push(readValType(r));
    return { kind: "func", ft: { params, results } };
  }
  if (form === 0x5e) {
    const elem = readStorage(r);
    r.u8(); // mutability
    return { kind: "array", elem };
  }
  if (form === 0x5f) {
    const fields: ("i8" | "i16" | "i32" | "ref")[] = [];
    for (let n = r.uleb(); n > 0; n--) {
      fields.push(readStorage(r));
      r.u8();
    }
    return { kind: "struct", fields };
  }
  throw new Error(`wasm2c: type form 0x${form.toString(16)} is outside the subset`);
}

export function decodeModule(bytes: Uint8Array): Module {
  const r = new Reader(bytes);
  const magic = r.bytes(8);
  if (magic[0] !== 0 || magic[1] !== 0x61) throw new Error("wasm2c: not a wasm module");
  const m: Module = { types: [], funcTypes: [], globals: [], exports: new Map(), data: [], bodies: [], names: new Map() };
  while (r.pos < bytes.length) {
    const id = r.u8();
    const size = r.uleb();
    const end = r.pos + size;
    switch (id) {
      case 0: {
        const name = r.name();
        if (name === "name") {
          while (r.pos < end) {
            const sub = r.u8();
            const subEnd = r.uleb() + r.pos;
            if (sub === 1) {
              for (let n = r.uleb(); n > 0; n--) {
                const idx = r.uleb();
                m.names.set(idx, r.name());
              }
            }
            r.pos = subEnd;
          }
        }
        r.pos = end;
        break;
      }
      case 1:
        for (let n = r.uleb(); n > 0; n--) {
          if (r.b[r.pos] === 0x4e) {
            r.pos++;
            for (let k = r.uleb(); k > 0; k--) m.types.push(readComp(r));
          } else m.types.push(readComp(r));
        }
        break;
      case 2:
        if (r.uleb() !== 0) throw new Error("wasm2c: imports are outside the subset");
        break;
      case 3:
        for (let n = r.uleb(); n > 0; n--) m.funcTypes.push(r.uleb());
        break;
      case 6:
        for (let n = r.uleb(); n > 0; n--) {
          const t = readValType(r);
          r.u8();
          const op = r.u8();
          let init: string;
          if (op === 0x41) init = cI32(r.sleb());
          else if (op === 0xd0) {
            r.sleb();
            init = "0";
          } else throw new Error(`wasm2c: global initializer 0x${op.toString(16)} is outside the subset`);
          if (r.u8() !== 0x0b) throw new Error("wasm2c: global initializer is not a single constant");
          m.globals.push({ t, init });
        }
        break;
      case 7:
        for (let n = r.uleb(); n > 0; n--) {
          const name = r.name();
          const kind = r.u8();
          const idx = r.uleb();
          if (kind !== 0) throw new Error("wasm2c: only function exports are in the subset");
          m.exports.set(idx, name);
        }
        break;
      case 12:
        r.uleb();
        break;
      case 10:
        for (let n = r.uleb(); n > 0; n--) {
          const bodyEnd = r.uleb() + r.pos;
          const locals: VT[] = [];
          for (let runs = r.uleb(); runs > 0; runs--) {
            const count = r.uleb();
            const t = readValType(r);
            for (let k = 0; k < count; k++) locals.push(t);
          }
          m.bodies.push({ locals, code: r.b.subarray(r.pos, bodyEnd) });
          r.pos = bodyEnd;
        }
        break;
      case 11:
        for (let n = r.uleb(); n > 0; n--) {
          if (r.u8() !== 0x01) throw new Error("wasm2c: only passive data segments are in the subset");
          m.data.push(r.bytes(r.uleb()));
        }
        break;
      default:
        throw new Error(`wasm2c: section ${id} is outside the subset`);
    }
    r.pos = end;
  }
  return m;
}

function cI32(v: number): string {
  v |= 0;
  return v === -2147483648 ? "(-2147483647 - 1)" : String(v);
}

function cName(s: string): string {
  return s.replace(/[^A-Za-z0-9_]/g, "_").replace(/_+/g, "_").replace(/^_|_$/g, "");
}

function cType(t: VT): string {
  return t === "i32" ? "int32_t" : "RxObj *";
}

/** A value on the symbolic operand stack: a C expression, the locals it
 * reads, and whether it reads globals or GC memory (the hazards a write
 * must flush). */
interface SE {
  c: string;
  t: VT;
  locals: ReadonlySet<number>;
  glob: boolean;
  mem: boolean;
}

const NO_LOCALS: ReadonlySet<number> = new Set();

interface Frame {
  kind: "block" | "loop" | "if" | "func";
  id: number;
  height: number;
  results: VT[];
  resultVars: string[];
  hasElse: boolean;
  dead: boolean;
}

export interface Wasm2cOptions {
  /** prefix for every emitted C identifier */
  prefix: string;
  /** C names for exported functions: export name → C function name */
  exportName: (name: string) => string;
}

export interface Wasm2cResult {
  /** the whole translation: prelude, types, data, globals, functions, GC */
  c: string;
  /** type index of each array/struct, for the host's layout macros */
  types: Comp[];
}

/** Translates `bytes` (a module inside the subset) to C. */
export function wasmToC(bytes: Uint8Array, opts: Wasm2cOptions): Wasm2cResult {
  const m = decodeModule(bytes);
  const P = opts.prefix;
  const out: string[] = [];
  const fnName = new Map<number, string>();
  const used = new Set<string>();
  m.funcTypes.forEach((_, i) => {
    const exp = m.exports.get(i);
    let n = exp !== undefined ? opts.exportName(exp) : `${P}f_${cName(m.names.get(i) ?? `f${i}`)}`;
    if (used.has(n)) n = `${n}_${i}`;
    used.add(n);
    fnName.set(i, n);
  });
  const ftOf = (typeIdx: number): FuncType => {
    const t = m.types[typeIdx];
    if (t === undefined || t.kind !== "func") throw new Error(`wasm2c: type ${typeIdx} is not a function type`);
    return t.ft;
  };
  const multi = new Map<string, string>();
  const retType = (ft: FuncType): string => {
    if (ft.results.length === 0) return "void";
    if (ft.results.length === 1) return cType(ft.results[0]!);
    const key = ft.results.map((t) => (t === "i32" ? "i" : "r")).join("");
    let n = multi.get(key);
    if (n === undefined) {
      n = `${P}res_${key}`;
      multi.set(key, n);
    }
    return n;
  };
  const sig = (i: number): string => {
    const ft = ftOf(m.funcTypes[i]!);
    const params = ft.params.map((t, k) => (t === "i32" ? `int32_t p${k}` : `RxObj *p${k}`)).join(", ");
    return `${m.exports.has(i) ? API : "static"} ${retType(ft)} ${fnName.get(i)!}(${params.length > 0 ? params : "void"})`;
  };
  const API = `${P.toUpperCase()}API`;
  const DECLS = `${P.toUpperCase()}DECLS_ONLY`;
  // Pre-compute every function's return type so the multi-result structs
  // are known before the bodies.
  m.funcTypes.forEach((t) => retType(ftOf(t)));

  const elemSize = (e: "i8" | "i16" | "i32" | "ref"): string => (e === "i8" ? "1" : e === "i16" ? "2" : e === "i32" ? "4" : "sizeof(RxObj *)");

  // ── the host's view: the object model, the checked accessors, the
  // entry points (exports) and the collector's controls. A host that links
  // the engine as its own object defines DECLS_ONLY (and API as extern)
  // before including; the engine's own unit defines API empty; a host
  // including everything in one unit defines neither (all static).
  out.push(preludeDecls(P));
  for (const [key, n] of multi) {
    out.push(`typedef struct { ${[...key].map((ch, k) => `${ch === "i" ? "int32_t" : "RxObj *"} v${k};`).join(" ")} } ${n};`);
  }
  for (const i of m.exports.keys()) out.push(`${sig(i)};`);
  out.push("");
  out.push(`#ifndef ${DECLS}`);
  out.push(preludeImpl(P));
  // ── type table for the marker: kind (0 function, 1 array of scalars,
  // 2 array of references, 3 struct) and a struct's reference-field mask
  out.push(`static const unsigned char ${P}type_kind[${m.types.length}] = {${m.types.map((t) => (t.kind === "func" ? 0 : t.kind === "array" ? (t.elem === "ref" ? 2 : 1) : 3)).join(", ")}};`);
  for (const t of m.types) {
    if (t.kind === "struct" && t.fields.length > 32) throw new Error("wasm2c: a struct of more than 32 fields is outside the subset");
  }
  out.push(
    `static const uint32_t ${P}struct_refs[${m.types.length}] = {${m.types
      .map((t) => (t.kind === "struct" ? `0x${t.fields.reduce((acc, f, k) => (f === "ref" ? acc + 2 ** k : acc), 0).toString(16)}u` : "0"))
      .join(", ")}};`,
  );
  out.push(gcMark(P));
  out.push("");

  // ── data
  m.data.forEach((seg, i) => {
    const lines: string[] = [];
    for (let k = 0; k < seg.length; k += 24) lines.push("  " + Array.from(seg.subarray(k, k + 24), (b) => `${b},`).join(""));
    out.push(`static const uint8_t ${P}data${i}[${Math.max(seg.length, 1)}] = {\n${seg.length > 0 ? lines.join("\n") : "  0"}\n};`);
  });
  out.push("");

  // ── globals
  m.globals.forEach((g, i) => out.push(`static ${cType(g.t)}${g.t === "ref" ? "" : " "}${P}g${i} = ${g.init};`));
  out.push("");

  // ── prototypes (the exports' are above)
  m.funcTypes.forEach((_, i) => {
    if (!m.exports.has(i)) out.push(`${sig(i)};`);
  });
  out.push("");

  // ── bodies
  m.bodies.forEach((body, i) => {
    out.push(translateBody(m, i, body, { P, fnName, ftOf, retType, sig: sig(i), elemSize }));
    out.push("");
  });

  // ── the collector's roots
  const refGlobals = m.globals.map((g, i) => (g.t === "ref" ? i : -1)).filter((i) => i >= 0);
  out.push(`static void ${P}mark_roots(void) {`);
  for (const i of refGlobals) out.push(`  ${P}mark(${P}g${i});`);
  out.push(`}`);
  // ── every global back to its initial value (free_all's second half)
  out.push(`static void ${P}reset_globals(void) {`);
  m.globals.forEach((g, i) => out.push(`  ${P}g${i} = ${g.init};`));
  out.push(`}`);
  out.push(gcCollect(P));
  out.push(`#endif /* ${DECLS} */`);
  return { c: out.join("\n"), types: m.types };
}

interface Ctx {
  P: string;
  fnName: Map<number, string>;
  ftOf: (t: number) => FuncType;
  retType: (ft: FuncType) => string;
  sig: string;
  elemSize: (e: "i8" | "i16" | "i32" | "ref") => string;
}

function translateBody(m: Module, fi: number, body: Body, cx: Ctx): string {
  const { P } = cx;
  const ft = cx.ftOf(m.funcTypes[fi]!);
  const localTypes: VT[] = [...ft.params, ...body.locals];
  const lname = (k: number): string => (k < ft.params.length ? `p${k}` : `l${k}`);
  const decls: string[] = [];
  for (let k = ft.params.length; k < localTypes.length; k++) decls.push(`  ${cType(localTypes[k]!)}${localTypes[k] === "ref" ? "" : " "}l${k} = 0;`);
  const lines: string[] = [];
  const labelUses = new Map<string, number>();
  let tempN = 0;
  const temp = (t: VT): string => {
    const n = `${t === "i32" ? "t" : "r"}${tempN++}`;
    decls.push(`  ${cType(t)}${t === "ref" ? "" : " "}${n};`);
    return n;
  };
  const multiTemp = (ty: string): string => {
    const n = `m${tempN++}`;
    decls.push(`  ${ty} ${n};`);
    return n;
  };
  const emit = (s: string): void => {
    lines.push(`  ${s}`);
  };
  const goto = (l: string): string => {
    labelUses.set(l, (labelUses.get(l) ?? 0) + 1);
    return `goto ${l};`;
  };

  const stack: SE[] = [];
  const atom = (c: string, t: VT): SE => ({ c, t, locals: NO_LOCALS, glob: false, mem: false });
  const pop = (): SE => {
    const v = stack.pop();
    if (v === undefined) throw new Error(`wasm2c: operand stack underflow in function ${fi}`);
    return v;
  };
  const materialize = (e: SE): SE => {
    if (/^[trm]\d+$/.test(e.c) || /^-?\d+$/.test(e.c)) return { ...e, locals: NO_LOCALS, glob: false, mem: false };
    const n = temp(e.t);
    emit(`${n} = ${e.c};`);
    return atom(n, e.t);
  };
  const flushIf = (pred: (e: SE) => boolean): void => {
    for (let k = 0; k < stack.length; k++) if (pred(stack[k]!)) stack[k] = materialize(stack[k]!);
  };
  const spillAll = (): void => flushIf(() => true);
  const merge = (c: string, t: VT, ...xs: SE[]): SE => {
    const locals = new Set<number>();
    for (const x of xs) for (const l of x.locals) locals.add(l);
    return { c, t, locals, glob: xs.some((x) => x.glob), mem: xs.some((x) => x.mem) };
  };
  const pushEffect = (c: string, t: VT): void => {
    const n = temp(t);
    emit(`${n} = ${c};`);
    stack.push(atom(n, t));
  };

  const frames: Frame[] = [];
  let frameN = 0;
  const blockResults = (r: Reader): VT[] => {
    const b = r.b[r.pos]!;
    if (b === 0x40) {
      r.pos++;
      return [];
    }
    if (b === 0x7f || b === 0x63 || b === 0x64) return [readValType(r)];
    const idx = r.sleb();
    const bt = cx.ftOf(idx);
    if (bt.params.length > 0) throw new Error("wasm2c: block parameters are outside the subset");
    return bt.results;
  };
  const top = (): Frame => frames[frames.length - 1]!;
  const assignResults = (f: Frame): void => {
    // the top f.results.length values → the frame's result variables
    const vals = f.results.map(() => pop()).reverse();
    vals.forEach((v, k) => emit(`${f.resultVars[k]} = ${v.c};`));
  };
  const returnStmt = (): void => {
    const vals = ft.results.map(() => pop()).reverse();
    if (vals.length === 0) emit("return;");
    else if (vals.length === 1) emit(`return ${vals[0]!.c};`);
    else emit(`return (${cx.retType(ft)}){${vals.map((v) => v.c).join(", ")}};`);
  };
  /** The label a branch to frame f jumps to. */
  const target = (f: Frame): string => (f.kind === "loop" ? `L${f.id}` : `E${f.id}x`);
  const branch = (depth: number): void => {
    const f = frames[frames.length - 1 - depth];
    if (f === undefined) throw new Error("wasm2c: branch depth out of range");
    if (f.kind === "func") {
      // The values stay on the stack for a br_if's fall-through (a br or
      // br_table truncates after); the caller materialized them.
      const vals = f.results.map(() => pop()).reverse();
      vals.forEach((v) => stack.push(v));
      returnStmt();
      vals.forEach((v) => stack.push(v));
      return;
    }
    if (f.kind === "loop") {
      emit(goto(target(f)));
      return;
    }
    if (f.results.length > 0) {
      const vals = f.results.map(() => pop()).reverse();
      vals.forEach((v, k) => emit(`${f.resultVars[k]} = ${v.c};`));
      vals.forEach((v) => stack.push(v));
    }
    emit(goto(target(f)));
  };

  frames.push({ kind: "func", id: frameN++, height: 0, results: ft.results, resultVars: [], hasElse: false, dead: false });

  const r = new Reader(body.code);
  const i32bin = (op: (a: string, b: string) => string): void => {
    const b = pop();
    const a = pop();
    stack.push(merge(op(a.c, b.c), "i32", a, b));
  };
  const U = (x: string): string => `(uint32_t)(${x})`;
  const W = (x: string): string => `(int32_t)(${x})`;
  const arrElem = (ti: number): "i8" | "i16" | "i32" | "ref" => {
    const t = m.types[ti];
    if (t === undefined || t.kind !== "array") throw new Error(`wasm2c: type ${ti} is not an array type`);
    return t.elem;
  };
  let deadDepth = 0;
  let lastDead = false;
  while (r.pos < r.b.length) {
    const op = r.u8();
    const f = top();
    if (f.dead) {
      // Unreachable code: decode (so the structure stays matched) but emit
      // nothing until this frame's else/end.
      if (op === 0x02 || op === 0x03 || op === 0x04) {
        blockResults(r);
        deadDepth++;
        continue;
      }
      if (op === 0x0b && deadDepth > 0) {
        deadDepth--;
        continue;
      }
      if (op === 0x05 && deadDepth > 0) continue;
      if (op !== 0x0b && op !== 0x05) {
        skipImmediates(op, r);
        continue;
      }
    }
    switch (op) {
      case 0x00: // unreachable
        emit(`${P}trap();`);
        f.dead = true;
        stack.length = f.height;
        break;
      case 0x01:
        break;
      case 0x02: // block
      case 0x03: // loop
      case 0x04: {
        // if
        const results = blockResults(r);
        let cond: SE | null = null;
        if (op === 0x04) cond = pop();
        spillAll();
        const id = frameN++;
        const fr: Frame = {
          kind: op === 0x02 ? "block" : op === 0x03 ? "loop" : "if",
          id,
          height: stack.length,
          results,
          resultVars: results.map((t) => temp(t)),
          hasElse: false,
          dead: false,
        };
        frames.push(fr);
        if (op === 0x03) {
          lines.push(`L${id}:;`);
        } else if (op === 0x04) {
          emit(`if (!(${cond!.c})) ${goto(`E${id}e`)}`);
        }
        break;
      }
      case 0x05: {
        // else
        if (f.kind !== "if") throw new Error("wasm2c: else outside an if");
        if (!f.dead) {
          assignResults(f);
          emit(goto(`E${f.id}x`));
        }
        stack.length = f.height;
        lines.push(`E${f.id}e:;`);
        labelUses.set(`E${f.id}e`, (labelUses.get(`E${f.id}e`) ?? 0) + 1);
        f.hasElse = true;
        f.dead = false;
        break;
      }
      case 0x0b: {
        // end
        frames.pop();
        if (f.kind === "func") {
          lastDead = f.dead;
          if (!f.dead) returnStmt();
          if (r.pos !== r.b.length) throw new Error("wasm2c: code after the function's end");
          break;
        }
        if (!f.dead) assignResults(f);
        stack.length = f.height;
        if (f.kind === "if" && !f.hasElse) {
          lines.push(`E${f.id}e:;`);
          labelUses.set(`E${f.id}e`, (labelUses.get(`E${f.id}e`) ?? 0) + 1);
        }
        if (f.kind !== "loop") lines.push(`E${f.id}x:;`);
        for (let k = 0; k < f.results.length; k++) stack.push(atom(f.resultVars[k]!, f.results[k]!));
        break;
      }
      case 0x0c: {
        branch(r.uleb());
        f.dead = true;
        stack.length = f.height;
        break;
      }
      case 0x0d: {
        // br_if
        const depth = r.uleb();
        const cond = pop();
        const tf = frames[frames.length - 1 - depth]!;
        const n = tf.kind === "loop" ? 0 : tf.results.length;
        if (n > 0) {
          for (let k = stack.length - n; k < stack.length; k++) stack[k] = materialize(stack[k]!);
        }
        const c = materialize(cond);
        const save = lines.length;
        branch(depth);
        const body2 = lines.splice(save).map((l) => l.trim());
        emit(`if (${c.c}) { ${body2.join(" ")} }`);
        break;
      }
      case 0x0e: {
        // br_table
        const n = r.uleb();
        const labels: number[] = [];
        for (let k = 0; k < n; k++) labels.push(r.uleb());
        const dflt = r.uleb();
        const idx = materialize(pop());
        // Every target takes the same values (validation); materialize them
        // once, so each arm can assign them to its own target.
        const arity = (d: number): number => {
          const tf = frames[frames.length - 1 - d];
          if (tf === undefined) throw new Error("wasm2c: branch depth out of range");
          return tf.kind === "loop" ? 0 : tf.results.length;
        };
        const nv = arity(dflt);
        for (const d of labels) if (arity(d) !== nv) throw new Error("wasm2c: br_table targets of different arity");
        for (let k = stack.length - nv; k < stack.length; k++) stack[k] = materialize(stack[k]!);
        emit(`switch ((uint32_t)${idx.c}) {`);
        labels.forEach((d, k) => {
          const save = lines.length;
          branch(d);
          const b = lines.splice(save).map((l) => l.trim());
          emit(`  case ${k}u: ${b.join(" ")}`);
        });
        {
          const save = lines.length;
          branch(dflt);
          const b = lines.splice(save).map((l) => l.trim());
          emit(`  default: ${b.join(" ")}`);
        }
        emit(`}`);
        f.dead = true;
        stack.length = f.height;
        break;
      }
      case 0x0f:
        returnStmt();
        f.dead = true;
        stack.length = f.height;
        break;
      case 0x10: {
        const callee = r.uleb();
        const cft = cx.ftOf(m.funcTypes[callee]!);
        const args = cft.params.map(() => pop()).reverse();
        flushIf((e) => e.glob || e.mem);
        const call = `${cx.fnName.get(callee)!}(${args.map((a) => a.c).join(", ")})`;
        if (cft.results.length === 0) emit(`${call};`);
        else if (cft.results.length === 1) pushEffect(call, cft.results[0]!);
        else {
          const mt = multiTemp(cx.retType(cft));
          emit(`${mt} = ${call};`);
          cft.results.forEach((t, k) => stack.push(atom(`${mt}.v${k}`, t)));
          // keep each result its own temp (a later call reuses nothing, but
          // a result read after a second call of the same callee must not
          // see the newer struct)
          for (let k = stack.length - cft.results.length; k < stack.length; k++) {
            const n = temp(stack[k]!.t);
            emit(`${n} = ${stack[k]!.c};`);
            stack[k] = atom(n, stack[k]!.t);
          }
        }
        break;
      }
      case 0x1a: {
        // drop
        pop();
        break;
      }
      case 0x20: {
        const k = r.uleb();
        stack.push({ c: lname(k), t: localTypes[k]!, locals: new Set([k]), glob: false, mem: false });
        break;
      }
      case 0x21:
      case 0x22: {
        const k = r.uleb();
        const v = pop();
        flushIf((e) => e.locals.has(k));
        emit(`${lname(k)} = ${v.c};`);
        if (op === 0x22) stack.push({ c: lname(k), t: localTypes[k]!, locals: new Set([k]), glob: false, mem: false });
        break;
      }
      case 0x23: {
        const g = r.uleb();
        stack.push({ c: `${P}g${g}`, t: m.globals[g]!.t, locals: NO_LOCALS, glob: true, mem: false });
        break;
      }
      case 0x24: {
        const g = r.uleb();
        const v = pop();
        flushIf((e) => e.glob);
        emit(`${P}g${g} = ${v.c};`);
        break;
      }
      case 0x41:
        stack.push(atom(cI32(r.sleb()), "i32"));
        break;
      case 0x45: {
        const a = pop();
        stack.push(merge(`(${a.c} == 0)`, "i32", a));
        break;
      }
      case 0x46:
        i32bin((a, b) => `(${a} == ${b})`);
        break;
      case 0x47:
        i32bin((a, b) => `(${a} != ${b})`);
        break;
      case 0x48:
        i32bin((a, b) => `(${a} < ${b})`);
        break;
      case 0x49:
        i32bin((a, b) => `(${U(a)} < ${U(b)})`);
        break;
      case 0x4a:
        i32bin((a, b) => `(${a} > ${b})`);
        break;
      case 0x4b:
        i32bin((a, b) => `(${U(a)} > ${U(b)})`);
        break;
      case 0x4c:
        i32bin((a, b) => `(${a} <= ${b})`);
        break;
      case 0x4d:
        i32bin((a, b) => `(${U(a)} <= ${U(b)})`);
        break;
      case 0x4e:
        i32bin((a, b) => `(${a} >= ${b})`);
        break;
      case 0x4f:
        i32bin((a, b) => `(${U(a)} >= ${U(b)})`);
        break;
      case 0x6a:
        i32bin((a, b) => W(`${U(a)} + ${U(b)}`));
        break;
      case 0x6b:
        i32bin((a, b) => W(`${U(a)} - ${U(b)}`));
        break;
      case 0x6c:
        i32bin((a, b) => W(`${U(a)} * ${U(b)}`));
        break;
      case 0x6d:
        i32bin((a, b) => `${P}div_s(${a}, ${b})`);
        break;
      case 0x6e:
        i32bin((a, b) => `${P}div_u(${a}, ${b})`);
        break;
      case 0x6f:
        i32bin((a, b) => `${P}rem_s(${a}, ${b})`);
        break;
      case 0x70:
        i32bin((a, b) => `${P}rem_u(${a}, ${b})`);
        break;
      case 0x71:
        i32bin((a, b) => `(${a} & ${b})`);
        break;
      case 0x72:
        i32bin((a, b) => `(${a} | ${b})`);
        break;
      case 0x73:
        i32bin((a, b) => `(${a} ^ ${b})`);
        break;
      case 0x74:
        i32bin((a, b) => W(`${U(a)} << (${b} & 31)`));
        break;
      case 0x75:
        i32bin((a, b) => `${P}shr_s(${a}, ${b})`);
        break;
      case 0x76:
        i32bin((a, b) => W(`${U(a)} >> (${b} & 31)`));
        break;
      case 0xd0: {
        r.sleb();
        stack.push(atom("((RxObj *)0)", "ref"));
        break;
      }
      case 0xd1: {
        const a = pop();
        stack.push(merge(`(${a.c} == 0)`, "i32", a));
        break;
      }
      case 0xfb: {
        const sub = r.uleb();
        switch (sub) {
          case 0x00: {
            // struct.new
            const ti = r.uleb();
            const st = m.types[ti];
            if (st === undefined || st.kind !== "struct") throw new Error("wasm2c: struct.new of a non-struct type");
            const vals = st.fields.map(() => pop()).reverse();
            const n = temp("ref");
            emit(`${n} = ${P}new_struct(${ti}, ${st.fields.length});`);
            vals.forEach((v, k) => emit(st.fields[k] === "ref" ? `${P}sf(${n})[${k}].r = ${v.c};` : `${P}sf(${n})[${k}].i = ${v.c};`));
            stack.push(atom(n, "ref"));
            break;
          }
          case 0x02: {
            // struct.get
            const ti = r.uleb();
            const fidx = r.uleb();
            const st = m.types[ti];
            if (st === undefined || st.kind !== "struct") throw new Error("wasm2c: struct.get of a non-struct type");
            const a = pop();
            const fk = st.fields[fidx]!;
            if (fk === "i8" || fk === "i16") throw new Error("wasm2c: packed struct fields are outside the subset");
            stack.push({ ...merge(`${P}sf(${P}nn(${a.c}))[${fidx}].${fk === "ref" ? "r" : "i"}`, fk === "ref" ? "ref" : "i32", a), mem: true });
            break;
          }
          case 0x07: {
            // array.new_default
            const ti = r.uleb();
            const len = pop();
            pushEffect(`${P}new_array(${ti}, ${cx.elemSize(arrElem(ti))}, ${len.c})`, "ref");
            break;
          }
          case 0x08: {
            // array.new_fixed
            const ti = r.uleb();
            const n = r.uleb();
            const e = arrElem(ti);
            const vals: SE[] = [];
            for (let k = 0; k < n; k++) vals.push(pop());
            vals.reverse();
            const t = temp("ref");
            emit(`${t} = ${P}new_array(${ti}, ${cx.elemSize(e)}, ${n});`);
            vals.forEach((v, k) => emit(`${P}set_${e}(${t}, ${k}, ${v.c});`));
            stack.push(atom(t, "ref"));
            break;
          }
          case 0x09: {
            // array.new_data
            const ti = r.uleb();
            const di = r.uleb();
            const len = pop();
            const off = pop();
            const seg = m.data[di];
            if (seg === undefined) throw new Error("wasm2c: array.new_data names a missing segment");
            pushEffect(`${P}new_data(${ti}, ${cx.elemSize(arrElem(ti))}, ${P}data${di}, ${seg.length}, ${off.c}, ${len.c})`, "ref");
            break;
          }
          case 0x0b:
          case 0x0c:
          case 0x0d: {
            // array.get / get_s / get_u
            const ti = r.uleb();
            const e = arrElem(ti);
            const idx = pop();
            const a = pop();
            let fn: string;
            if (e === "i8") fn = sub === 0x0c ? "get_s8" : "get_u8";
            else if (e === "i16") fn = sub === 0x0c ? "get_s16" : "get_u16";
            else fn = `get_${e}`;
            if ((e === "i32" || e === "ref") && sub !== 0x0b) throw new Error("wasm2c: get_s/get_u on an unpacked array");
            stack.push({ ...merge(`${P}${fn}(${a.c}, ${idx.c})`, e === "ref" ? "ref" : "i32", a, idx), mem: true });
            break;
          }
          case 0x0e: {
            // array.set
            const ti = r.uleb();
            const e = arrElem(ti);
            const v = pop();
            const idx = pop();
            const a = pop();
            flushIf((x) => x.mem);
            emit(`${P}set_${e}(${a.c}, ${idx.c}, ${v.c});`);
            break;
          }
          case 0x0f: {
            // array.len
            const a = pop();
            stack.push(merge(`${P}len(${a.c})`, "i32", a));
            break;
          }
          case 0x11: {
            // array.copy
            const dt = r.uleb();
            const st = r.uleb();
            const n = pop();
            const si = pop();
            const s = pop();
            const di = pop();
            const d = pop();
            const de = arrElem(dt);
            if (de !== arrElem(st)) throw new Error("wasm2c: array.copy between element types");
            flushIf((x) => x.mem);
            emit(`${P}copy(${d.c}, ${di.c}, ${s.c}, ${si.c}, ${n.c}, ${cx.elemSize(de)});`);
            break;
          }
          default:
            throw new Error(`wasm2c: GC instruction 0xfb ${sub} is outside the subset (function ${fi})`);
        }
        break;
      }
      default:
        throw new Error(`wasm2c: instruction 0x${op.toString(16)} is outside the subset (function ${fi})`);
    }
  }
  if (frames.length !== 0) throw new Error(`wasm2c: unbalanced control in function ${fi}`);
  // Drop the labels nothing jumps to.
  const kept = lines.filter((l) => {
    const mm = /^([LE]\d+[ex]?):;$/.exec(l);
    return mm === null || (labelUses.get(mm[1]!) ?? 0) > 0;
  });
  // A value function whose end is unreachable still needs a C ending (the
  // trap never returns).
  if (ft.results.length > 0 && lastDead) kept.push(`  ${P}trap();`);
  return `${cx.sig} {\n${decls.join("\n")}${decls.length > 0 ? "\n" : ""}${kept.join("\n")}\n}`;
}

/** Skips an instruction's immediates (unreachable code is decoded, never
 * translated). */
function skipImmediates(op: number, r: Reader): void {
  switch (op) {
    case 0x0c:
    case 0x0d:
    case 0x10:
    case 0x20:
    case 0x21:
    case 0x22:
    case 0x23:
    case 0x24:
      r.uleb();
      return;
    case 0x0e: {
      const n = r.uleb();
      for (let k = 0; k <= n; k++) r.uleb();
      return;
    }
    case 0x41:
    case 0xd0:
      r.sleb();
      return;
    case 0xfb: {
      const sub = r.uleb();
      switch (sub) {
        case 0x00:
        case 0x07:
        case 0x0b:
        case 0x0c:
        case 0x0d:
        case 0x0e:
          r.uleb();
          return;
        case 0x0f:
          return;
        case 0x02:
        case 0x08:
        case 0x09:
        case 0x11:
          r.uleb();
          r.uleb();
          return;
        default:
          throw new Error(`wasm2c: GC instruction 0xfb ${sub} is outside the subset`);
      }
    }
    default:
      if ((op >= 0x45 && op <= 0x76) || op === 0x00 || op === 0x01 || op === 0x0f || op === 0x1a || op === 0xd1) return;
      throw new Error(`wasm2c: instruction 0x${op.toString(16)} is outside the subset`);
  }
}

/** The object model, the checked accessors and the collector's controls:
 * what a host sees. */
function preludeDecls(P: string): string {
  const U = P.toUpperCase();
  const H = `${U}HDR`;
  const D = `${U}PAYLOAD`;
  const API = `${U}API`;
  return `/* ── object model ─────────────────────────────────────────────────────
 * Every GC object is one allocation: this header, then the payload (array
 * elements, or a struct's fields as RxVal slots). Objects the translated
 * code allocates are linked on ${P}all and freed by ${P}collect(); a
 * FOREIGN object (the host's, e.g. a regex's bytecode) is never on that
 * list, never freed by the collector and never traced. */
typedef struct RxObj {
  struct RxObj *next;
  int32_t type;
  int32_t mark;
  int32_t len;
  int32_t foreign;
} RxObj;
typedef union {
  int32_t i;
  RxObj *r;
} RxVal;
#define ${H} ((sizeof(RxObj) + 7u) & ~(size_t)7u)
#define ${D}(o) ((void *)((char *)(o) + ${H}))

#ifndef ${API}
#define ${API} static
#endif
/* The host provides these two. */
${API} _Noreturn void ${P}trap(void);
${API} _Noreturn void ${P}oom(void);
/* Extra roots the host holds across a collection it asks for between
 * calls (a match loop's subject and capture array). */
#define ${U}NPIN 4
#ifdef ${U}DECLS_ONLY
${API} RxObj *${P}all;
${API} size_t ${P}since;
${API} RxObj *${P}pin[${U}NPIN];
#else
${API} RxObj *${P}all = 0;
${API} size_t ${P}since = 0;
${API} RxObj *${P}pin[${U}NPIN] = {0};
#endif
${API} RxObj *${P}new_array(int32_t type, size_t esz, int32_t len);
${API} void ${P}collect(void);
${API} void ${P}free_all(void);
static inline RxVal *${P}sf(RxObj *o) { return (RxVal *)${D}(o); }
static inline RxObj *${P}nn(RxObj *o) {
  if (!o) ${P}trap();
  return o;
}
static inline int32_t ${P}len(RxObj *o) { return ${P}nn(o)->len; }
static inline void ${P}bound(RxObj *o, int32_t i) {
  if (!o || (uint32_t)i >= (uint32_t)o->len) ${P}trap();
}
static inline int32_t ${P}get_u8(RxObj *o, int32_t i) {
  ${P}bound(o, i);
  return ((uint8_t *)${D}(o))[i];
}
static inline int32_t ${P}get_s8(RxObj *o, int32_t i) {
  ${P}bound(o, i);
  return ((int8_t *)${D}(o))[i];
}
static inline int32_t ${P}get_u16(RxObj *o, int32_t i) {
  ${P}bound(o, i);
  return ((uint16_t *)${D}(o))[i];
}
static inline int32_t ${P}get_s16(RxObj *o, int32_t i) {
  ${P}bound(o, i);
  return ((int16_t *)${D}(o))[i];
}
static inline int32_t ${P}get_i32(RxObj *o, int32_t i) {
  ${P}bound(o, i);
  return ((int32_t *)${D}(o))[i];
}
static inline RxObj *${P}get_ref(RxObj *o, int32_t i) {
  ${P}bound(o, i);
  return ((RxObj **)${D}(o))[i];
}
static inline void ${P}set_i8(RxObj *o, int32_t i, int32_t v) {
  ${P}bound(o, i);
  ((uint8_t *)${D}(o))[i] = (uint8_t)v;
}
static inline void ${P}set_i16(RxObj *o, int32_t i, int32_t v) {
  ${P}bound(o, i);
  ((uint16_t *)${D}(o))[i] = (uint16_t)v;
}
static inline void ${P}set_i32(RxObj *o, int32_t i, int32_t v) {
  ${P}bound(o, i);
  ((int32_t *)${D}(o))[i] = v;
}
static inline void ${P}set_ref(RxObj *o, int32_t i, RxObj *v) {
  ${P}bound(o, i);
  ((RxObj **)${D}(o))[i] = v;
}
`;
}

/** The allocator and the checked arithmetic the translation calls. */
function preludeImpl(P: string): string {
  const U = P.toUpperCase();
  const H = `${U}HDR`;
  const D = `${U}PAYLOAD`;
  const API = `${U}API`;
  return `static RxObj *${P}alloc(int32_t type, size_t payload, int32_t len) {
  RxObj *o = (RxObj *)calloc(1, ${H} + payload);
  if (!o) ${P}oom();
  o->type = type;
  o->len = len;
  o->next = ${P}all;
  ${P}all = o;
  ${P}since += ${H} + payload;
  return o;
}
${API} RxObj *${P}new_array(int32_t type, size_t esz, int32_t len) {
  /* wasm reads the length unsigned: past 2^31 it is out of range, a trap */
  if (len < 0) ${P}trap();
  return ${P}alloc(type, esz * (size_t)len, len);
}
static RxObj *${P}new_struct(int32_t type, int32_t n) { return ${P}alloc(type, sizeof(RxVal) * (size_t)n, n); }
/* array.new_data: elements read little-endian from the passive segment. */
static RxObj *${P}new_data(int32_t type, size_t esz, const uint8_t *seg, size_t seglen, int32_t off, int32_t len) {
  if (len < 0 || (uint64_t)(uint32_t)off + (uint64_t)(uint32_t)len * esz > (uint64_t)seglen) ${P}trap();
  RxObj *o = ${P}new_array(type, esz, len);
  const uint8_t *s = seg + (uint32_t)off;
  for (int32_t k = 0; k < len; k++) {
    if (esz == 1) ((uint8_t *)${D}(o))[k] = s[k];
    else if (esz == 2) ((uint16_t *)${D}(o))[k] = (uint16_t)(s[2 * k] | (s[2 * k + 1] << 8));
    else ((int32_t *)${D}(o))[k] = (int32_t)((uint32_t)s[4 * k] | ((uint32_t)s[4 * k + 1] << 8) | ((uint32_t)s[4 * k + 2] << 16) | ((uint32_t)s[4 * k + 3] << 24));
  }
  return o;
}
static void ${P}copy(RxObj *d, int32_t di, RxObj *s, int32_t si, int32_t n, size_t esz) {
  if (!d || !s) ${P}trap();
  if ((uint64_t)(uint32_t)di + (uint32_t)n > (uint64_t)(uint32_t)d->len || (uint64_t)(uint32_t)si + (uint32_t)n > (uint64_t)(uint32_t)s->len) ${P}trap();
  memmove((char *)${D}(d) + (size_t)(uint32_t)di * esz, (char *)${D}(s) + (size_t)(uint32_t)si * esz, (size_t)(uint32_t)n * esz);
}
static inline int32_t ${P}div_s(int32_t a, int32_t b) {
  if (b == 0 || (a == INT32_MIN && b == -1)) ${P}trap();
  return a / b;
}
static inline int32_t ${P}div_u(int32_t a, int32_t b) {
  if (b == 0) ${P}trap();
  return (int32_t)((uint32_t)a / (uint32_t)b);
}
static inline int32_t ${P}rem_s(int32_t a, int32_t b) {
  if (b == 0) ${P}trap();
  return b == -1 ? 0 : a % b;
}
static inline int32_t ${P}rem_u(int32_t a, int32_t b) {
  if (b == 0) ${P}trap();
  return (int32_t)((uint32_t)a % (uint32_t)b);
}
static inline int32_t ${P}shr_s(int32_t a, int32_t b) {
  /* arithmetic: the sign bit shifts in (wasm i32.shr_s) */
  uint32_t n = (uint32_t)b & 31u;
  uint32_t u = (uint32_t)a >> n;
  if (a < 0 && n > 0) u |= ~(0xffffffffu >> n);
  return (int32_t)u;
}
`;
}

function gcMark(P: string): string {
  const D = `${P.toUpperCase()}PAYLOAD`;
  return `/* ── the collector: mark from the module's reference globals, sweep the
 * allocation list. The host calls ${P}collect() only between top-level
 * calls, never while it still needs an object the translation allocated. */
static void ${P}mark(RxObj *o) {
  if (!o || o->mark || o->foreign) return;
  o->mark = 1;
  if (${P}type_kind[o->type] == 2) {
    for (int32_t k = 0; k < o->len; k++) ${P}mark(((RxObj **)${D}(o))[k]);
  } else if (${P}type_kind[o->type] == 3) {
    uint32_t refs = ${P}struct_refs[o->type];
    for (int32_t k = 0; k < o->len; k++)
      if (refs & (1u << k)) ${P}mark(${P}sf(o)[k].r);
  }
}`;
}

function gcCollect(P: string): string {
  return `${P.toUpperCase()}API void ${P}collect(void) {
  ${P}mark_roots();
  for (int k = 0; k < ${P.toUpperCase()}NPIN; k++) ${P}mark(${P}pin[k]);
  RxObj **pp = &${P}all;
  while (*pp) {
    RxObj *o = *pp;
    if (o->mark) {
      o->mark = 0;
      pp = &o->next;
    } else {
      *pp = o->next;
      free(o);
    }
  }
  ${P}since = 0;
}
/* Frees every object, reachable or not, and puts every global back to its
 * initial value: the module as if never run (process exit, a library
 * reset). */
${P.toUpperCase()}API void ${P}free_all(void) {
  while (${P}all) {
    RxObj *o = ${P}all;
    ${P}all = o->next;
    free(o);
  }
  ${P}since = 0;
  for (int k = 0; k < ${P.toUpperCase()}NPIN; k++) ${P}pin[k] = 0;
  ${P}reset_globals();
}`;
}
