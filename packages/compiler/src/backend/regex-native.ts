/* The native lanes' regex engine, rendered from the wasm tier's (follow-up
 * unit D, "native regex = wasm = Node").
 *
 * renderNativeRegexEngine() translates the standalone regex engine module
 * (wasm/regex-engine-module.ts: the ONE compiler, the matcher, the regex
 * value) to C with wasm2c.ts. scripts/gen-native-regex-engine.mjs writes
 * the result to packages/runtime/src/scr_regex_engine.h, which
 * scr_regex.c includes; native-regex-engine-drift.test.ts requires the
 * checked-in file to equal a fresh rendering, so the native engine cannot
 * drift from the wasm one. */
import type { IrModule, SrcLoc } from "../ir/nodes.js";
import { wasmToC } from "./wasm2c.js";
import { regexEngineModule } from "./wasm/regex-engine-module.js";
import { foldRegexLiteral } from "./wasm/regex-fold.js";

/** The native lanes' build-time verdict on the module's regex literals —
 * the wasm tier's own (regex-fold.ts, the one compiler run at build time):
 * the first literal it refuses, by the same key (`expr:regexLit:<key>`: a
 * fence of SEMANTICS.md S102, or `invalid-pattern` for a pattern Node
 * rejects, an early SyntaxError), or null. A generic walk over the IR —
 * `kind` discriminants live only on IR objects. */
export function nativeRegexLiteralRefusal(mod: IrModule): { kind: string; loc: SrcLoc } | null {
  let found: { kind: string; loc: SrcLoc } | null = null;
  const visit = (v: unknown): void => {
    if (found !== null || v === null || typeof v !== "object") return;
    if (Array.isArray(v)) {
      for (const item of v) visit(item);
      return;
    }
    const node = v as { kind?: unknown; pattern?: unknown; flags?: unknown; loc?: SrcLoc };
    if (node.kind === "regexLit" && typeof node.pattern === "string" && typeof node.flags === "string") {
      const lit = foldRegexLiteral(node.pattern, node.flags);
      if (lit.kind === "refuse") {
        found = { kind: `expr:regexLit:${lit.key}`, loc: node.loc! };
        return;
      }
    }
    for (const key of Object.keys(v)) visit((v as Record<string, unknown>)[key]);
  };
  visit(mod);
  return found;
}

/** A native regex literal's canonical .flags (dgimsuvy order), from the
 * same build-time compile; the literal was checked by
 * nativeRegexLiteralRefusal before emission. */
export function nativeRegexLiteralFlags(pattern: string, flags: string): string {
  const lit = foldRegexLiteral(pattern, flags);
  if (lit.kind !== "ok") throw new Error(`internal: regex literal /${pattern}/${flags} reached a native emitter refused (${lit.key})`);
  return lit.flags;
}

export const NATIVE_REGEX_ENGINE_PATH = "packages/runtime/src/scr_regex_engine.h";

export function renderNativeRegexEngine(): string {
  const mod = regexEngineModule();
  const { c } = wasmToC(mod.bytes, { prefix: "scr_rx_", exportName: (n) => `scr_rx_${n}` });
  const t = mod.types;
  return `/* GENERATED by scripts/gen-native-regex-engine.mjs -- do not edit by hand.
 *
 * The native lanes' regular-expression engine: the WasmGC tier's regex
 * engine module (packages/compiler/src/backend/wasm/regex-engine-module.ts
 * -- the ONE regex compiler regex-compiler.ts, the matcher
 * regex-interpreter.ts and the regex value regex-value.ts) translated to C
 * by packages/compiler/src/backend/wasm2c.ts. Every native verdict,
 * SyntaxError message, fence, .source, .flags and match is therefore the
 * wasm tier's own (SEMANTICS.md S065, S102).
 * packages/compiler/test/native-regex-engine-drift.test.ts re-renders it
 * and requires this file byte for byte.
 *
 * scr_regex_engine.c compiles it (SCR_RX_API empty: the entry points
 * external) into an object cc.ts caches per flavor; scr_regex.c includes it
 * for the declarations only (SCR_RX_DECLS_ONLY, SCR_RX_API extern), defines
 * scr_rx_trap() and scr_rx_oom(), and calls scr_rx_collect() at safe
 * points. Included with neither macro, everything is static (one unit). */
#ifndef SCR_REGEX_ENGINE_H
#define SCR_REGEX_ENGINE_H

#include <stdint.h>
#include <stdlib.h>
#include <string.h>

/* The GC types the host builds and reads. */
#define SCR_RX_T_STR ${t.str} /* (array (mut i16)): UTF-16 code units */
#define SCR_RX_T_BC ${t.bc} /* (array (mut i8)): bytecode */
#define SCR_RX_T_CAP ${t.cap} /* (array (mut i32)): capture slots */
#define SCR_RX_T_REGEX ${t.regex} /* struct: source, flags, bytecode, capture count, group names */
#define SCR_RX_T_STRARR ${t.strArr} /* (array (mut (ref null str))): group names */

${c}

#endif /* SCR_REGEX_ENGINE_H */
`;
}
