/* ── directives (differential.test.ts's twins) ───────────────────────── */
function directiveHead(file: string): string[] {
  return readFileSync(file, "utf8").split("\n", 2);
}
function expectedExitCode(file: string): number {
  for (const line of directiveHead(file)) {
    const m = /^\/\/ @exit:\s*(\d+)\s*$/.exec(line);
    if (m) return Number(m[1]);
  }
  return 0;
}
function wantsDynamic(file: string): boolean {
  return directiveHead(file).some((l) => /^\/\/ @dynamic\s*$/.test(l));
}
function programInputs(file: string): string[] {
  if (!/\/main\.(ts|js|mjs|cjs)$/.test(file)) return [file];
  return [
    ...ENTRY_EXTS.flatMap((ext) => globSync(join(file, `../**/*.${ext}`))),
    ...globSync(join(file, "../**/tsconfig.json")),
    ...globSync(join(file, "../**/package.json")),
  ].sort();
}

/* ── the Node oracle (wasm-differential.test.ts's twin) ──────────────── */
const comptimeShim = pathToFileURL(join(import.meta.dirname, "comptime-shim.mjs")).href;
const islandShim = pathToFileURL(join(import.meta.dirname, "island-shim.mjs")).href;

function wantsTransformTypes(file: string): boolean {
  if (directiveHead(file).some((l) => /^\/\/ @transform-types\s*$/.test(l))) return true;
  return programInputs(file).some((f) => /\benum\s+[A-Za-z_$]/.test(readFileSync(f, "utf8")));
}
function wantsTscDecorators(file: string): boolean {
  return directiveHead(file).some((l) => /^\/\/ @tsc-decorators\s*$/.test(l));
}
function nodeOracleFile(file: string): string {
  if (!wantsTscDecorators(file)) return file;
  const src = readFileSync(file, "utf8");
  const out = ts5.transpileModule(src, {
    compilerOptions: { target: ts5.ScriptTarget.ES2022, module: ts5.ModuleKind.ESNext },
    fileName: file,
  }).outputText;
  const key = createHash("sha256").update(ts5.version).update("\0").update(src).digest("hex").slice(0, 16);
  const path = join(cacheDir, `dec-oracle-${key}.mjs`);
  mkdirSync(cacheDir, { recursive: true });
  const tmp = `${path}.${process.pid}.tmp`;
  writeFileSync(tmp, out);
  renameSync(tmp, path);
  return path;
}
function wantsNoDeprecation(file: string): boolean {
  return directiveHead(file).some((l) => /^\/\/ @no-deprecation\s*$/.test(l));
}
function nodeOracleArgs(file: string): string[] {
  const transform = wantsTransformTypes(file) ? ["--experimental-transform-types", "--disable-warning=ExperimentalWarning"] : [];
  const nodep = wantsNoDeprecation(file) ? ["--no-deprecation"] : [];
  return [...transform, ...nodep, "--import", comptimeShim, "--import", islandShim, nodeOracleFile(file)];
}

interface RunResult {
  stdout: Buffer;
  stderr: Buffer;
  exitCode: number;
}

/** Runs a child to completion with its stdin closed at once (corpus
 * programs may read fd 0 to EOF), tolerating a nonzero exit. */
async function runChild(cmd: string, args: string[]): Promise<RunResult> {
  const pending = execFileAsync(cmd, args, { encoding: "buffer", maxBuffer: 256 << 20, timeout: 240_000 });
  pending.child.stdin?.end();
  try {
    const { stdout, stderr } = await pending;
    return { stdout, stderr, exitCode: 0 };
  } catch (err) {
    const e = err as { code?: unknown; stdout?: Buffer; stderr?: Buffer; signal?: unknown };
    if (typeof e.code !== "number" || !Buffer.isBuffer(e.stdout) || !Buffer.isBuffer(e.stderr)) throw err;
    return { stdout: e.stdout, stderr: e.stderr, exitCode: e.code };
  }
}

/* ── at most N programs in flight ────────────────────────────────────── */
const width = Math.max(1, Number(process.env["SCRIPTC_TEST_WORKERS"] ?? "4") || 4);
let inFlight = 0;
const waiters: (() => void)[] = [];
async function slot<T>(f: () => Promise<T>): Promise<T> {
  while (inFlight >= width) await new Promise<void>((r) => waiters.push(r));
  inFlight++;
  try {
    return await f();
  } finally {
    inFlight--;
    waiters.shift()?.();
  }
}

async function build(file: string) {
  const hash = createHash("sha256");
  for (const f of programInputs(file)) hash.update(f).update(readFileSync(f));
  const key = hash.update("wasm-native").update(wantsDynamic(file) ? "dyn" : "").digest("hex").slice(0, 16);
  const outDir = join(cacheDir, `wn-${key}`);
  return compile(file, {
    outPath: join(outDir, "program"),
    outDir,
    dynamic: wantsDynamic(file),
    backend: "wasm-native",
  });
}

const claimed: string[] = [];
const refusalKinds = new Map<string, number>();
const refusalPrograms = new Map<string, string[]>();

/** A refusal's census key: this lane's own refusal names its kind last
 * (`host:<import>`, `wasm2c:<what>`); a wasm-tier refusal names its kind
 * first, as the wasm lane's census reads it. */
function refusalKey(message: string): string {
  const kinds = [...message.matchAll(/\(([^()]+)\)/g)].map((m) => m[1]!);
  return (message.startsWith("the wasm-native lane") ? kinds[kinds.length - 1] : kinds[0]) ?? "?";
}

/** SCRIPTC_WASMNATIVE_GC_STRESS=n runs every executable with the collector
 * forced every n allocations (wn_gc.c's WN_GC_STRESS): the corpus then
 * exercises the collector, which its small heaps otherwise rarely reach. */
const gcStress = process.env["SCRIPTC_WASMNATIVE_GC_STRESS"];
if (gcStress !== undefined && gcStress !== "") process.env["WN_GC_STRESS"] = gcStress;

describe(`wasm-native differential corpus (${files.length} programs${shardSuffix()})`, () => {
  test.concurrent.for(files.map((f) => [f.slice(corpusDir.length + 1), f] as const))("%s", async ([rel, file]) => {
    await slot(async () => {
      const res = await build(file);
      if (!res.ok) {
        // Out of the lane: LOUD, and exactly the one refusal.
        expect(res.diagnostics.map((d) => d.code)).toEqual(["SC3001"]);
        const kind = refusalKey(res.diagnostics[0]!.message);
        refusalKinds.set(kind, (refusalKinds.get(kind) ?? 0) + 1);
        refusalPrograms.set(kind, [...(refusalPrograms.get(kind) ?? []), rel]);
        return;
      }
      claimed.push(rel);
      expect(res.backend).toBe("wasm-native");
      // The oracle first, then the executable: never both at once (a
      // program writing relative to the cwd would race itself).
      const node = await runChild("node", nodeOracleArgs(file));
      const native = await runChild(res.binaryPath, []);
      if (!native.stdout.equals(node.stdout)) {
        expect(native.stdout.toString("utf8")).toBe(node.stdout.toString("utf8"));
        expect.unreachable("wasm-native-vs-node stdout differed at byte level but not after utf8 decode");
      }
      const expectedExit = expectedExitCode(file);
      if (expectedExit === 0 && !native.stderr.equals(node.stderr)) {
        expect(native.stderr.toString("utf8")).toBe(node.stderr.toString("utf8"));
        expect.unreachable("wasm-native-vs-node stderr differed at byte level but not after utf8 decode");
      }
      expect(native.exitCode).toBe(expectedExit);
      expect(node.exitCode).toBe(expectedExit);
    });
  });

  test("claim floor: EXACTLY the claimed set, both directions", () => {
    const floorHere = new Set(shardSelect(CLAIM_FLOOR, (n) => n));
    const claimedHere = new Set(claimed);
    const missingFromClaimed = [...floorHere].filter((n) => !claimedHere.has(n)).sort();
    const missingFromFloor = [...claimedHere].filter((n) => !floorHere.has(n)).sort();
    expect(
      { missingFromClaimed, missingFromFloor },
      missingFromClaimed.length || missingFromFloor.length
        ? `CLAIM_FLOOR and the claimed set disagree — pinned-but-not-claimed (regressions): ${JSON.stringify(missingFromClaimed)}; claimed-but-not-pinned (unpinned new claims): ${JSON.stringify(missingFromFloor)}`
        : undefined,
    ).toEqual({ missingFromClaimed: [], missingFromFloor: [] });
  });

  afterAll(() => {
    const top = (m: Map<string, number>, n: number): string =>
      [...m]
        .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
        .slice(0, n)
        .map(([k, c]) => `${k}×${c}`)
        .join(", ");
    /* eslint-disable no-console */
    console.info(`wasm-native lane: ${claimed.length}/${files.length} corpus programs claimed; refusals by reason: ${top(refusalKinds, 40)}`);
    if (process.env["SCRIPTC_WASMNATIVE_REFUSALS"] === "1") {
      console.info(`  claimed: ${[...claimed].sort().join(" ")}`);
      for (const [kind] of [...refusalKinds].sort((a, b) => b[1] - a[1])) console.info(`  ${kind}: ${refusalPrograms.get(kind)!.sort().join(" ")}`);
    }
    /* eslint-enable no-console */
  });
});
