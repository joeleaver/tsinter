for (const s of SAMPLES) {
  const steps: string[] = [];
  let index = 0;
  outer: while (index < s.length) {
    for (const [name, re] of BLOCKS) {
      re.lastIndex = index;
      if (re.test(s)) {
        steps.push(`${name}@${index}-${re.lastIndex}`);
        index = re.lastIndex;
        continue outer;
      }
      if (re.lastIndex !== 0) steps.push(`!${name}@${index}:${re.lastIndex}`);
    }
    steps.push(`none@${index}`);
    index += 1;
  }
  console.log(`[${hex(s)}] ${steps.join(" ")}`);
  for (const re of [EMOJI_RE, CJKT_WIDE_RE]) {
    const hits: string[] = [];
    for (let i = 0; i <= s.length; i++) {
      re.lastIndex = i;
      const m = re.exec(s);
      if (m !== null) hits.push(`${m.index}:${hex(m[0])}>${re.lastIndex}`);
      else if (re.lastIndex !== 0) hits.push(`miss${i}>${re.lastIndex}`);
    }
    console.log(`  ${re.flags} ${hits.join(" | ")}`);
  }
  console.log(`  modifiers stripped: [${hex(s.replaceAll(MODIFIER_RE, ""))}] ${MODIFIER_RE.lastIndex}`);
}

